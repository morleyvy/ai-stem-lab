const N = '(-?[\\d,]+)'; // число в формате fmt(): запятая как десятичный разделитель
const re = (src) => new RegExp(`^${src}$`);
const w = (ru) => DICT[ru] ?? ru;

// Часть записи журнала про одну пробирку: «с <реактивом> — <что видно> (<вещество>: <масса> мг)»
const PART = [
  [new RegExp(`^с аммиачным раствором Ag₂O — (.+) \\(Ag: ${N} мг\\)$`), (m, look, mass) => `Ag₂O-ның аммиактағы ерітіндісімен — ${w(look)} (Ag: ${mass} мг)`],
  [new RegExp(`^с Cu\\(OH\\)₂ — (.+) \\(Cu₂O: ${N} мг\\)$`), (m, look, mass) => `Cu(OH)₂-мен — ${w(look)} (Cu₂O: ${mass} мг)`],
];
const part = (ru) => {
  for (const [r, fn] of PART) if (r.test(ru)) return ru.replace(r, fn);
  return ru;
};

export const patterns = [
  [re(`(Метаналь|Этаналь|Пропанон), ${N} °C: реактивы ещё не добавлены`), (m, name, t) => `${w(name)}, ${t} °C: реактивтер әлі қосылған жоқ`],
  [re(`(Метаналь|Этаналь|Пропанон), ${N} °C: (.+)`), (m, name, t, rest) => `${w(name)}, ${t} °C: ${rest.split('; ').map(part).join('; ')}`],
];
