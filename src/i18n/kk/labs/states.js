const N = '(-?[\\d,]+)'; // число в формате fmt(): запятая как десятичный разделитель
const re = (src) => new RegExp(`^${src}$`);

// Хвост описания про холодное стекло (src/sims/states.js, GLASS_SUFFIX)
const TAILS = {
  '': '',
  '; холодное стекло сухое': '; суық шыны құрғақ',
  '; холодное стекло слегка запотело': '; суық шыны сәл терледі',
  '; на холодном стекле пар конденсируется в капли воды': '; суық шыныда бу су тамшыларына конденсацияланады',
};
const TAIL = '((?:; холодное стекло (?:сухое|слегка запотело))|(?:; на холодном стекле пар конденсируется в капли воды))?';

// Основная часть описания после «t мин, P Вт: »
const BODY = [
  [new RegExp(`^температура льда ${N} °C — лёд ещё не тает$`), 'мұздың температурасы $1 °C — мұз әлі ерімейді'],
  [new RegExp(`^идёт плавление при 0 °C — растаяло ${N} г льда из ${N} г$`), '0 °C-та балқу жүріп жатыр — $2 г мұздың $1 г-ы еріді'],
  [new RegExp(`^весь лёд растаял за ${N} мин, вода нагрелась до ${N} °C$`), 'бүкіл мұз $1 минутта еріді, су $2 °C-қа дейін қызды'],
  [new RegExp(`^вода кипит при 100 °C уже ${N} мин, выкипело ${N} г$`), 'су 100 °C-та $1 минуттан бері қайнап жатыр, $2 г қайнап кетті'],
  [/^вся вода выкипела$/, 'бүкіл су қайнап кетті'],
];
const body = (text) => {
  for (const [r, kk] of BODY) if (r.test(text)) return text.replace(r, kk);
  return text;
};
const BODY_SRC = '(температура льда .+? — лёд ещё не тает|идёт плавление при 0 °C — растаяло .+?|весь лёд растаял за .+?|вода кипит при 100 °C уже .+?|вся вода выкипела)';

