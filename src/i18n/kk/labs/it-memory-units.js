// Шығыс септігінің жалғауы санның соңғы сөзіне қарай: 400-ден, 30-дан, 1000-нан, 40-тан
const LAST_WORD_SUFFIX = {
  units: ['ден', 'ден', 'ден', 'тен', 'тен', 'тен', 'дан', 'ден', 'ден', 'дан'], // нөл, бір, екі, үш, төрт, бес, алты, жеті, сегіз, тоғыз
  tens: ['', 'нан', 'дан', 'дан', 'тан', 'ден', 'тан', 'тен', 'нен', 'нан'], // он, жиырма, отыз, қырық, елу, алпыс, жетпіс, сексен, тоқсан
};
function abl(raw) {
  const n = Number(String(raw).replace(/\D/g, ''));
  let suffix;
  if (n === 0 || n % 10) suffix = LAST_WORD_SUFFIX.units[n % 10];
  else if (n % 100) suffix = LAST_WORD_SUFFIX.tens[(n % 100) / 10];
  else if (n % 1000) suffix = 'ден'; // жүз
  else suffix = 'нан'; // мың, миллион
  return `${raw}-${suffix}`;
}
// Объём «из» ёмкости: 1 Гбайттан, 512 Мбайттан — у «байт» твёрдый слог, жалғау всегда -тан
const fromVolume = (v) => `${v}тан`;
const files = (folder, sz) => `${w(folder)}, әрқайсысы ${sz}`;

