const N = '([+−-]?[\\d,]+)'; // число в формате fmt(): запятая как десятичный разделитель, знак Δt
const re = (src) => new RegExp(`^${src}$`);
const LIQ = '(воды|соляной кислоты)';
// «в 100 мл воды» → «100 мл суда», «100 мл воды» → «100 мл су»
const inLiq = (liq) => (liq === 'воды' ? 'суда' : 'тұз қышқылында');
const ofLiq = (liq) => (liq === 'воды' ? 'су' : 'тұз қышқылы');

export const patterns = [
  [re(`${N} мл ${LIQ}`), (m, v, liq) => `${v} мл ${ofLiq(liq)}`],
  [re(`В калориметре ${N} мл ${LIQ} при ${N} °C`), (m, v, liq, t) => `Калориметрде ${t} °C температурадағы ${v} мл ${ofLiq(liq)}`],
  [re(`(NaOH|NH₄NO₃) в ${N} мл ${LIQ}`), (m, f, v, liq) => `${v} мл ${liq === 'воды' ? 'судағы' : 'тұз қышқылындағы'} ${f}`],
  [
    re(`(NaOH|NH₄NO₃) \\(${N} г\\) в ${N} мл ${LIQ}: температура (повысилась|понизилась) до ${N} °C, Δt = ${N} °C; (выделилось|поглотилось) ${N} кДж теплоты(; кроме растворения идёт реакция нейтрализации)?`),
    (m, f, mass, v, liq, dir, t, dt, kind, q, neut) => `${f} (${mass} г) ${v} мл ${inLiq(liq)}: температура ${dir === 'повысилась' ? 'көтеріліп' : 'төмендеп'}, ${t} °C болды, Δt = ${dt} °C; ${q} кДж жылу ${kind === 'выделилось' ? 'бөлінді' : 'сіңірілді'}${neut ? '; еруден бөлек бейтараптану реакциясы жүреді' : ''}`,
  ],
];
