// Время реакции человека — опыт с падающей линейкой. Партнёр держит линейку длиной 50 см за верхний
// конец, нулевая отметка — между пальцами ученика. Партнёр без предупреждения отпускает линейку,
// ученик ловит её; по отметке h, на которой сомкнулись пальцы, время реакции находят из закона
// свободного падения: h = g·t²/2, t = √(2h/g).
// Сигнал к ловле — зрительный (видно, что линейка падает), звуковой (глаза закрыты, партнёр говорит
// «Хоп!») или тактильный (партнёр касается плеча). Тренировка (серия попыток) ускоряет реакцию,
// отвлечение внимания (счёт в уме) замедляет. Иллюстрация установки — в svg/scenes/nervous.js.

import { fmt } from './canvas.js';
import { nervousScene } from '../svg/scenes/nervous.js';

export const G = 9.8; // м/с² — как в школьных задачниках РК
export const RULER = 50; // см — длина линейки: дольше ≈ 0,32 с линейку уже не поймать

// Время простой реакции тренированного школьника на сигнал, с. На звук и касание реакция быстрее,
// чем на свет: в сетчатке превращение света в нервный импульс идёт через цепочку химических реакций
// и занимает несколько сотых секунды, а слуховые и кожные рецепторы срабатывают почти мгновенно.
// На касание плеча чуть медленнее, чем на звук: импульс идёт по нерву и спинному мозгу — путь длиннее.
const BASE = [0.19, 0.15, 0.16];
export const SIGNALS = ['зрительный', 'звуковой', 'тактильный'];
const SIGNAL_PHRASE = ['Зрительный сигнал', 'Звуковой сигнал', 'Тактильный сигнал'];

// Первая попытка на 20% медленнее: ученик ещё не знает, чего ждать. С тренировкой реакция быстро
// выходит на постоянное значение — к 5-й попытке разница меньше 2%, дальше улучшения почти нет:
// быстрее, чем импульс пройдёт по рефлекторной дуге, поймать нельзя.
export const practice = (n) => 1 + 0.2 * Math.exp(-(Math.max(1, n) - 1) / 1.5);
// Счёт в уме занимает внимание: мозг позже замечает сигнал, реакция медленнее примерно в 1,5 раза
const DISTRACT = 1.45;

// Истинное время реакции в попытке n (до неё сделано n − 1 попыток), с
export const reactionTime = (p, n = p.trial) => BASE[p.signal] * practice(n) * (p.distract ? DISTRACT : 1);

// Что видит ученик: отметку на линейке с точностью до 0,5 см (точнее по пальцам не прочесть)
// и время, вычисленное по этой отметке, — так же, как в настоящем опыте.
export function measure(p, n = p.trial) {
  const tTrue = reactionTime(p, n);
  const hTrue = (G * tTrue ** 2) / 2 * 100; // см
  if (hTrue > RULER) return { caught: false, h: hTrue, t: tTrue };
  const h = Math.round(hTrue * 2) / 2;
  return { caught: true, h, t: Math.sqrt((2 * h) / 100 / G) };
}

const MAX_T = Math.sqrt((2 * RULER) / 100 / G);

export default {
  id: 'nervous',
  subject: 'biology',
  title: 'Время реакции',
  freeTitle: 'Время реакции',
  freeSub: 'Падающая линейка, сигналы, рефлекторная дуга',
  controls: [
    // Сигнал и отвлечение выбирают только регуляторами: второй способ на сцене путал учеников
    { id: 'signal', label: 'Сигнал', min: 0, max: 2, step: 1, unit: '', value: 0, names: SIGNALS },
    { id: 'distract', label: 'Отвлечение', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['нет', 'счёт в уме'] },
    // Действие на сцене: щелчок по руке партнёра — он разжимает пальцы, линейка падает. Счётчик попыток — это и есть тренировка
    { id: 'trial', label: 'Попытки', min: 0, max: 10, step: 1, unit: '', value: 0, action: true, actionLabel: 'Отпустить линейку' },
  ],
  formula: 't = √(2h / g)',
  hint: 'Нажмите на руку партнёра — линейка упадёт, и вы её поймаете. Сигнал выбирайте регулятором.',
  theory: 'Нервная система воспринимает раздражения и управляет ответными действиями организма. Ответ на раздражение при участии нервной системы называют рефлексом, а путь нервного импульса — рефлекторной дугой: рецептор → чувствительный нейрон → центральная нервная система (головной и спинной мозг) → двигательный нейрон → рабочий орган (мышца). Время от сигнала до начала ответного движения — время реакции. Его можно измерить падающей линейкой: за время t она пролетает h = g·t²/2, значит t = √(2h/g).',

  readings(p) {
    if (!p.trial) {
      return [
        { label: 'Падение h', value: 'не измерено' },
        { label: 'Время реакции t', value: 'не измерено' },
        { label: 'Попыток', value: '0' },
      ];
    }
    const m = measure(p);
    return [
      { label: 'Падение h', value: m.caught ? `${fmt(m.h, 1)} см` : `не поймана (больше ${RULER} см)` },
      { label: 'Время реакции t', value: m.caught ? `${fmt(m.t, 2)} с` : `больше ${fmt(MAX_T, 2)} с` },
      { label: 'Попыток', value: String(p.trial) },
    ];
  },

  describe(p) {
    if (!p.trial) return 'Линейка ещё не отпущена — время реакции не измерено';
    const m = measure(p);
    // Номер попытки — это тренированность (сколько раз ловили), а не номер строки в листке: смена сигнала
    // даёт новую строку, но тренировки почти не добавляет, поэтому пишем «сделано попыток», а не «попытка №»
    const cond = `${SIGNAL_PHRASE[p.signal]}${p.distract ? ', счёт в уме' : ''}`;
    const tail = `(сделано попыток: ${p.trial})`;
    if (!m.caught) return `${cond}: линейка не поймана — пролетела больше ${RULER} см, t > ${fmt(MAX_T, 2)} с ${tail}`;
    return `${cond}: линейка пролетела h = ${fmt(m.h, 1)} см, время реакции t = ${fmt(m.t, 2)} с ${tail}`;
  },

  create(container, params, set) {
    return nervousScene(container, params, set, { measure, G });
  },
};
