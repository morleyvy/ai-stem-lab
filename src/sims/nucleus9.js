// Закон радиоактивного распада: образец радиоактивного изотопа лежит под счётчиком Гейгера.
// Ученик выбирает изотоп (у каждого свой период полураспада T½), включает счётчик и двигает время t,
// прошедшее с момента получения образца. Доля нераспавшихся ядер N/N₀ = 2^(−t/T½);
// скорость счёта пропорциональна числу распадов в единицу времени, то есть N/T½.
// Распад отдельного ядра случаен, а закон описывает поведение огромного числа ядер, поэтому
// на модели образца из 400 точек показано среднее: точек ровно столько, сколько даёт закон.
// Иллюстрация установки — в svg/scenes/nucleus9.js.

import { fmt } from './canvas.js';
import { nucleus9Scene } from '../svg/scenes/nucleus9.js';

export const DOTS = 400; // точек на модели образца
// Все три изотопа — β⁻-излучатели, применяемые в медицине: β-частицы свободно выходят из образца
// в тонкой оболочке и регистрируются счётчиком. Периоды полураспада — по справочным данным, округлённо.
export const ISOTOPES = [
  { name: 'Золото-198', short: 'Au-198', T: 2.7, color: '#eab308' },
  { name: 'Йод-131', short: 'I-131', T: 8, color: '#8b5cf6' },
  { name: 'Фосфор-32', short: 'P-32', T: 14.3, color: '#f97316' },
];
// Образцы приготовлены одновременно и содержат одинаковое число ядер. Тогда начальная скорость счёта
// обратно пропорциональна T½: чем быстрее распадаются ядра, тем чаще щёлкает счётчик.
// Коэффициент подобран так, чтобы свежий йод-131 давал 2000 имп/мин.
const K = 2000 * 8; // имп/мин · сут

export const isotope = (p) => ISOTOPES[p.iso];
export const fraction = (p) => 2 ** (-p.t / isotope(p).T);
export const alive = (p) => Math.round(DOTS * fraction(p));
export const countRate = (p) => (K / isotope(p).T) * fraction(p);

// Проценты: малые доли — с двумя значащими цифрами. Иначе у золота-198 к концу шкалы табло
// показало бы 0,00 %, будто распались все ядра, — а работа как раз учит, что так не бывает.
export const pct = (f) => fmt(f * 100, f >= 0.01 ? 1 : Math.max(2, Math.ceil(-Math.log10(f * 100)) + 1));
const rateText = (p) => (p.counter ? `${Math.round(countRate(p))} имп/мин` : 'выключен');

const sim = {
  id: 'nucleus9',
  freeTitle: 'Радиоактивный распад',
  freeSub: 'Период полураспада и счётчик Гейгера',
  subject: 'physics',
  title: 'Закон радиоактивного распада',
  controls: [
    { id: 't', label: 'Время после получения образца', min: 0, max: 48, step: 1, unit: 'сут', value: 0 },
    { id: 'iso', label: 'Образец под счётчиком', min: 0, max: 2, step: 1, unit: '', value: 1, names: ISOTOPES.map((x) => x.name), action: true, actionLabel: 'Щёлкнуть по свинцовому контейнеру с другим образцом' },
    { id: 'counter', label: 'Счётчик Гейгера', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['выключен', 'включён'], action: true, actionLabel: 'Включить счётчик Гейгера' },
  ],
  formula: 'N = N₀ · 2^(−t / T½)',
  hint: 'Щёлкните по радиометру, чтобы включить счётчик, и по свинцовому контейнеру, чтобы сменить образец. Время меняйте регулятором.',
  chart: { x: 't', y: (p) => fraction(p) * 100, xLabel: 't, сут', yLabel: 'N / N₀, %', series: (p) => isotope(p).name },
  theory: 'Ядра радиоактивных изотопов самопроизвольно распадаются, испуская излучение; при β-распаде ядро испускает электрон и превращается в ядро элемента с порядковым номером на единицу больше. Время, за которое распадается половина имеющихся радиоактивных ядер, называется периодом полураспада T½. За время t остаётся N = N₀ · 2^(−t/T½) ядер: через один период — половина, через два — четверть, через три — восьмая часть. Предсказать, когда распадётся отдельное ядро, нельзя: закон описывает огромное число ядер. Счётчик Гейгера регистрирует частицы, вылетающие при распадах, и щёлкает тем чаще, чем больше ядер распадается за секунду.',

  readings(p) {
    const iso = isotope(p);
    return [
      { label: 'Образец', value: `${iso.name}, T½ = ${String(iso.T).replace('.', ',')} сут` },
      { label: 'Время t', value: `${p.t} сут` },
      { label: 'Не распалось ядер', value: `${alive(p)} из ${DOTS} (${pct(fraction(p))} %)` },
      { label: 'Скорость счёта', value: rateText(p) },
    ];
  },

  describe(p) {
    const iso = isotope(p);
    const counter = p.counter ? `счётчик: ${Math.round(countRate(p))} имп/мин` : 'счётчик выключен';
    return `${iso.name}, t = ${p.t} сут: осталось ${pct(fraction(p))} % ядер (${alive(p)} из ${DOTS}), t/T½ = ${fmt(p.t / iso.T, 2)}; ${counter}`;
  },

  create(container, params, set) {
    return nucleus9Scene(container, params, set, { ISOTOPES, DOTS, fraction, countRate });
  },
};

export default sim;
