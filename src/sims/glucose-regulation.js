// Гормональная регуляция уровня глюкозы в крови. Испытуемый натощак пьёт раствор глюкозы (75 г, как
// в глюкозотолерантном тесте) или выполняет физическую нагрузку; глюкометр и монитор показывают,
// как меняется глюкоза в крови в течение трёх часов. Поджелудочная железа работает по принципу
// отрицательной обратной связи: β-клетки островков на рост глюкозы отвечают выбросом инсулина
// (клетки забирают глюкозу, печень запасает её в виде гликогена), α-клетки на снижение — выбросом
// глюкагона (печень расщепляет гликоген и отдаёт глюкозу в кровь). Модель «β-клетки не выделяют
// инсулин» — сахарный диабет I типа: глюкоза высокая уже натощак и после приёма почти не снижается.
// Уровни считаются численным интегрированием простой модели (минимальная модель глюкозы-инсулина
// с добавленным глюкагоном и гликогеном печени), а не задаются по шагам работы.
// Иллюстрация — в svg/scenes/glucose-regulation.js.

import { fmt } from './canvas.js';
import { glucoseScene } from '../svg/scenes/glucose-regulation.js';

export const NORM = [3.3, 5.5]; // ммоль/л — норма глюкозы натощак в капиллярной крови
export const RENAL = 10; // ммоль/л — почечный порог: выше него глюкоза попадает во вторичную мочу
export const T_MAX = 180; // мин — три часа наблюдения

// Состояние натощак у здорового человека: из него модель стартует, и в покое оно не меняется
const GB = 4.8; // ммоль/л
const IB = 8; // мкЕд/мл
const CB = 70; // пг/мл
const Y0 = 80; // г гликогена в печени утром натощак
const V = 17; // л — объём, в котором распределяется глюкоза (кровь и межклеточная жидкость)
const H0 = 0.06; // ммоль/(л·мин) — выход глюкозы из печени натощак
const DOSE = 75 / 0.18 / V; // 75 г глюкозы (M = 180 г/моль), пересчитанные на ммоль/л
const KA = 1 / 35; // 1/мин: всасывание в кишечнике идёт с пиком примерно через полчаса
// Потребление глюкозы: мозгом и эритроцитами — без инсулина, мышцами и жиром — с инсулином
const K_FREE = 0.008;
const K_INS = 0.0045;
const K_LIVER = 0.02; // запасание глюкозы печенью в гликоген под действием инсулина
// Работающие мышцы забирают глюкозу и без инсулина — поэтому при нагрузке инсулина нужно меньше
const K_LOAD = [0, 0.008, 0.02];

// Скорости изменения: глюкоза G, инсулин I, глюкагон C, гликоген печени Y
function rates({ G, I, C, Y }, t, p) {
  const absorb = p.meal ? DOSE * KA * KA * t * Math.exp(-KA * t) : 0;
  // Глюкагон усиливает расщепление гликогена, инсулин его тормозит; без гликогена расщеплять нечего
  const glycogenolysis = Y > 0 ? 0.5 * H0 * (C / CB) * 1.5 / (1 + 0.5 * I / IB) : 0;
  const gluconeogenesis = 0.5 * H0 * (0.5 + 0.5 * C / CB);
  const storage = K_LIVER * (I / IB) * Math.max(0, G - GB);
  const uptake = (K_FREE + K_INS * (I / IB) + K_LOAD[p.load]) * G;
  const urine = 0.05 * Math.max(0, G - RENAL);
  // β-клетки отвечают на глюкозу выше ≈ 3,5 ммоль/л, причём всё сильнее с её ростом
  const insulinOut = p.beta ? 0 : 0.324 * Math.max(0, G - 3.5) ** 1.5;
  // α-клетки: глюкагона больше, когда глюкоза низкая; инсулин соседних β-клеток его подавляет,
  // поэтому без инсулина глюкагон остаётся высоким даже при высокой глюкозе (как при диабете)
  const glucagonOut = 0.15 * CB * (GB / G) * (2 / (1 + I / IB)) * (1 + 0.25 * p.load);
  return {
    G: absorb + glycogenolysis + gluconeogenesis - storage - uptake - urine,
    I: insulinOut - 0.06 * I,
    C: glucagonOut - 0.15 * C,
    // Ночной расход гликогена не учитываем: в покое натощак запас за 3 часа заметно не меняется
    Y: V * 0.18 * (storage - glycogenolysis + 0.5 * H0),
  };
}

const DT = 0.25; // мин — шаг интегрирования

function integrate(start, p, minutes, sample) {
  let st = { ...start };
  const steps = Math.round(minutes / DT);
  for (let k = 0; k <= steps; k++) {
    if (sample && k % Math.round(1 / DT) === 0) sample.push(st);
    if (k === steps) break;
    const r = rates(st, k * DT, p);
    st = { G: st.G + r.G * DT, I: Math.max(0, st.I + r.I * DT), C: st.C + r.C * DT, Y: Math.max(0, st.Y + r.Y * DT) };
  }
  return st;
}

// Без инсулина натощак устанавливается своё, повышенное равновесие — его и берём за начало опыта
let diabeticFasting;
function fasting(beta) {
  if (!beta) return { G: GB, I: IB, C: CB, Y: Y0 };
  diabeticFasting ??= { ...integrate({ G: GB, I: 0, C: CB, Y: Y0 }, { beta: 1, meal: 0, load: 0 }, 1500), Y: Y0 };
  return diabeticFasting;
}

// Ход опыта по минутам 0…180 для данных условий (кэш: условий всего 12 сочетаний)
const cache = new Map();
export function course(p) {
  const key = `${p.beta}|${p.meal}|${p.load}`;
  if (!cache.has(key)) {
    const out = [];
    integrate(fasting(p.beta), p, T_MAX, out);
    cache.set(key, out);
  }
  return cache.get(key);
}

export const stateAt = (p, t = p.time) => course(p)[Math.max(0, Math.min(T_MAX, Math.round(t)))];

// Округляем так же, как показывает прибор, чтобы подпись «в норме» не расходилась с числом на экране
export function normText(G) {
  const g = Math.round(G * 10) / 10;
  if (g < NORM[0]) return 'ниже нормы';
  if (g > NORM[1]) return 'выше нормы';
  return 'в пределах нормы';
}

