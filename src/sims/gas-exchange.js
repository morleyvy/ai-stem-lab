// Спирометрия и газообмен. Ученик выдыхает в водяной спирометр: колокол всплывает ровно на объём
// выдохнутого воздуха. Три выдоха дают дыхательный объём (ДО), резервный объём выдоха (РОвыд)
// и жизненную ёмкость лёгких (ЖЁЛ); резервный объём вдоха считается: РОвд = ЖЁЛ − ДО − РОвыд.
// Выдохнутый воздух из колокола пропускают через известковую воду — она мутнеет от CO₂, а состав
// воздуха (как показал бы газоанализатор) выводится только в панели показаний. После приседаний
// дыхание становится чаще и глубже — минутный объём дыхания растёт в разы.
// Иллюстрация установки — в svg/scenes/gas-exchange.js.

import { fmt } from './canvas.js';
import { gasExchangeScene } from '../svg/scenes/gas-exchange.js';

// Объёмы лёгких подростка в покое по учебнику биологии 8 класса, мл
export const VC = 3500; // ЖЁЛ = ДО + РОвд + РОвыд
const TV_REST = 500;
const ERV_REST = 1500;
const RR_REST = 16; // дыхательных движений в минуту в покое

// Состав воздуха, %. Вдыхаемый — атмосферный; в альвеолах кислород уходит в кровь, а CO₂ приходит из неё.
export const AIR = { o2: 20.9, co2: 0.04 };
const ALV = { o2: 14.0, co2: 5.7 };
// «Вредное пространство» — воздух носоглотки, трахеи и бронхов (≈ 150 мл): он не участвует в газообмене
// и выходит при выдохе первым, разбавляя альвеолярный воздух. Поэтому выдыхаемый воздух — смесь
// вдыхаемого и альвеолярного, а при глубоком дыхании он ближе к альвеолярному.
const DEAD = 150;

export const MANEUVERS = ['не проводился', 'спокойный выдох', 'резервный выдох', 'выдох после максимального вдоха'];

// Сразу после приседаний дыхание учащается и углубляется: прибавки подобраны так, чтобы 20 приседаний
// давали ≈ 24 вдоха в минуту и ДО ≈ 0,9 л, как в школьных измерениях
export const rate = (p) => RR_REST + 0.4 * p.squats;
export const tidal = (p) => TV_REST + 20 * p.squats;
// ЖЁЛ от нагрузки не меняется: углубившийся вдох и выдох «съедают» часть резервных объёмов
export const expReserve = (p) => ERV_REST - 0.4 * (tidal(p) - TV_REST);
export const inspReserve = (p) => VC - tidal(p) - expReserve(p);
export const minuteVolume = (p) => (tidal(p) * rate(p)) / 1000; // л/мин

// Объём, который покажет спирометр после выдоха (номер выдоха — индекс в MANEUVERS)
export function spiroVolume(p, m = p.exhale) {
  if (m === 1) return tidal(p);
  if (m === 2) return expReserve(p);
  if (m === 3) return VC;
  return 0;
}

// Состав смешанного выдыхаемого воздуха при текущем спокойном дыхании
export function exhaled(p) {
  const f = DEAD / tidal(p);
  return { o2: f * AIR.o2 + (1 - f) * ALV.o2, co2: f * AIR.co2 + (1 - f) * ALV.co2 };
}

const pct = (v) => (v < 1 ? fmt(v, 2) : fmt(v, 1));
export const gasText = (g) => `O₂ ${pct(g.o2)}%, CO₂ ${pct(g.co2)}%`;
const state = (p) => (p.squats ? `После ${p.squats} приседаний` : 'В покое');

export default {
  id: 'gas-exchange',
  subject: 'biology',
  title: 'Спирометрия и газообмен',
  freeTitle: 'Объёмы лёгких',
  freeSub: 'Спирометр, ЖЁЛ, состав воздуха, нагрузка',
  controls: [
    { id: 'squats', label: 'Приседания перед измерением', min: 0, max: 40, step: 10, unit: 'раз', value: 0 },
    // Действия на сцене: каждый щелчок по мундштуку — следующий выдох по порядку измерений
    { id: 'exhale', label: 'Выдох в спирометр', min: 0, max: 3, step: 1, unit: '', value: 0, names: MANEUVERS, action: true, actionLabel: 'Выдохнуть в мундштук спирометра' },
    { id: 'lime', label: 'Опыт с известковой водой', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['не проведён', 'проведён'], action: true, actionLabel: 'Пропустить воздух из колокола через известковую воду' },
  ],
  formula: 'ЖЁЛ = ДО + РОвд + РОвыд;  МОД = ДО × ЧД',
  hint: 'Щёлкайте по мундштуку — три разных выдоха в спирометр. Щёлкните по красному крану на колоколе — воздух пойдёт в известковую воду.',
  chart: { x: 'squats', y: (p) => Math.round(minuteVolume(p) * 10) / 10, xLabel: 'приседания', yLabel: 'МОД, л/мин', series: () => 'минутный объём дыхания' },
  theory: 'Газообмен в лёгких идёт в альвеолах путём диффузии: кислород переходит из альвеолярного воздуха в кровь, углекислый газ — из крови в альвеолы. Поэтому во вдыхаемом воздухе около 20,9% кислорода и 0,04% углекислого газа, а в выдыхаемом — около 16% кислорода и 4% углекислого газа. Углекислый газ обнаруживают по помутнению известковой воды. При спокойном дыхании человек вдыхает и выдыхает около 500 мл воздуха — дыхательный объём (ДО). После спокойного вдоха можно дополнительно вдохнуть ещё около 1500 мл (резервный объём вдоха, РОвд), а после спокойного выдоха — выдохнуть ещё около 1500 мл (резервный объём выдоха, РОвыд). Жизненная ёмкость лёгких ЖЁЛ = ДО + РОвд + РОвыд ≈ 3500 мл; её измеряют спирометром. Минутный объём дыхания (МОД) — это ДО, умноженный на частоту дыхания (ЧД): в покое около 8 л/мин, при нагрузке — в несколько раз больше.',

  readings(p) {
    return [
      { label: 'Спирометр', value: p.exhale ? `${spiroVolume(p)} мл` : '—' },
      { label: 'Частота дыхания', value: `${rate(p)}/мин` },
      { label: 'Минутный объём', value: `${fmt(minuteVolume(p), 1)} л/мин` },
      // Состав выдыхаемого воздуха известен, только когда воздух из колокола проверили
      { label: 'Выдыхаемый воздух', value: p.lime && p.exhale ? gasText(exhaled(p)) : '—' },
    ];
  },

  // В журнал попадает итог последнего по порядку работы действия: нагрузка → известковая вода → спирометр
  describe(p) {
    if (p.squats) return `${state(p)}: ЧД ${rate(p)}/мин, ДО ${tidal(p)} мл, МОД ${fmt(minuteVolume(p), 1)} л/мин`;
    if (p.lime && p.exhale) return `Известковая вода помутнела. Выдыхаемый воздух: ${gasText(exhaled(p))}; вдыхаемый: ${gasText(AIR)}`;
    if (p.lime) return 'В колоколе нет выдыхаемого воздуха — известковая вода осталась прозрачной';
    if (p.exhale === 1) return `Спокойный выдох: дыхательный объём ${tidal(p)} мл`;
    if (p.exhale === 2) return `Резервный выдох после спокойного выдоха: ${expReserve(p)} мл`;
    if (p.exhale === 3) return `ЖЁЛ ${VC} мл = ДО ${tidal(p)} + РОвд ${inspReserve(p)} + РОвыд ${expReserve(p)} мл`;
    return `${state(p)}: ЧД ${rate(p)}/мин, ДО ${tidal(p)} мл, МОД ${fmt(minuteVolume(p), 1)} л/мин`;
  },

  create(container, params, set) {
    return gasExchangeScene(container, params, set, { spiroVolume, rate });
  },
};
