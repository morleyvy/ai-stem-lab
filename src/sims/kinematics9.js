// Равноускоренное движение: стальной шарик скатывается без начальной скорости по наклонному жёлобу.
// Электромагнит у старта держит шарик; щелчок отпускает его и запускает электронный секундомер, а оптический
// датчик, который ученик ставит на 0,1–1,6 м от старта, останавливает отсчёт и измеряет скорость шарика.
// Сила здесь не нужна: работа про кинематику — s = a·t²/2, v = a·t, a = 2s/t² и ряд путей 1 : 3 : 5 : 7.
// Законы Ньютона — отдельная работа dynamics9. Иллюстрация установки — в svg/scenes/kinematics9.js.

import { fmt } from './canvas.js';
import { kinematics9Scene } from '../svg/scenes/kinematics9.js';

const G = 9.8; // м/с² — как в школьных задачниках РК
export const END = 1.65; // м от старта до упора в конце жёлоба: за датчиком шарик ещё немного катится

// Шарик катится без проскальзывания, поэтому разгоняется медленнее, чем скользящее тело: a = (5/7)·g·sin α
// (часть энергии уходит во вращение сплошного шара). Ученику эта формула не нужна — ускорение он находит
// из опыта по a = 2s/t², но модель должна давать то, что показал бы настоящий жёлоб.
export const accel = (p) => (5 / 7) * G * Math.sin((p.alpha * Math.PI) / 180);
export const gateTime = (p) => Math.sqrt((2 * p.s) / accel(p));
export const gateSpeed = (p) => accel(p) * gateTime(p);

export default {
  id: 'kinematics9',
  subject: 'physics',
  title: 'Равноускоренное движение',
  freeTitle: 'Шарик на наклонном жёлобе',
  freeSub: 'Путь, время, ускорение, графики s(t) и v(t)',
  controls: [
    { id: 'alpha', label: 'Угол наклона жёлоба', min: 2, max: 10, step: 1, unit: '°', value: 5 },
    { id: 's', label: 'Расстояние до датчика', min: 0.1, max: 1.6, step: 0.1, unit: 'м', value: 0.1 },
    { id: 'released', label: 'Шарик', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['у старта', 'отпущен'], action: true, actionLabel: 'Отпустить шарик' },
  ],
  formula: 's = a·t²/2;  v = a·t;  a = 2s/t²',
  hint: 'Нажмите на шарик, чтобы отпустить его. Датчик тяните вдоль жёлоба, лапку штатива — вверх или вниз.',
  // На экране в сцене строятся s(t) и v(t); здесь — время до датчика при разных расстояниях и углах
  chart: { x: 's', y: gateTime, xLabel: 's, м', yLabel: 't, с', series: (p) => `α = ${p.alpha}°` },
  theory: 'Движение, при котором скорость тела за любые равные промежутки времени изменяется одинаково, называют равноускоренным. Если начальная скорость равна нулю, скорость растёт прямо пропорционально времени: v = a·t, а путь — пропорционально квадрату времени: s = a·t²/2. Поэтому ускорение можно найти по пути и времени движения: a = 2s/t². Пути, пройденные телом за последовательные равные промежутки времени, относятся как ряд нечётных чисел: 1 : 3 : 5 : 7 … График s(t) — парабола, график v(t) — прямая, выходящая из начала координат.',

  readings(p) {
    if (!p.released) {
      return [
        { label: 'Шарик', value: 'у старта' },
        { label: 'Угол α', value: `${p.alpha}°` },
        { label: 'Путь s', value: `${fmt(p.s, 1)} м` },
      ];
    }
    return [
      { label: 'Путь s', value: `${fmt(p.s, 1)} м` },
      { label: 'Время t', value: `${fmt(gateTime(p), 3)} с` },
      { label: 'Ускорение a', value: `${fmt(accel(p))} м/с²` },
      { label: 'Скорость v', value: `${fmt(gateSpeed(p))} м/с` },
    ];
  },

  describe(p) {
    if (!p.released) return `Шарик у старта; α = ${p.alpha}°, датчик на расстоянии s = ${fmt(p.s, 1)} м`;
    return `α = ${p.alpha}°: путь s = ${fmt(p.s, 1)} м пройден за t = ${fmt(gateTime(p), 3)} с; a = ${fmt(accel(p))} м/с², v = ${fmt(gateSpeed(p))} м/с`;
  },

  create(container, params, set) {
    return kinematics9Scene(container, params, set, { accel, gateTime, END });
  },
};
