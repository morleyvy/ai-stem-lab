// Движение тела, брошенного под углом к горизонту: баллистический пистолет стреляет стальным шариком,
// шарик падает на горизонтальный лоток на той же высоте, с которой вылетел. Ученик меняет угол вылета α
// (поворачивает ствол по транспортиру) и начальную скорость v₀ (сжатие пружины), стреляет и измеряет
// дальность полёта L по мерной ленте и время полёта по секундомеру.
// Сопротивление воздуха не учитываем: тяжёлый шарик при скоростях до 4 м/с тормозится воздухом
// пренебрежимо мало, а школьные формулы 10 класса записаны именно для этого случая.
// Иллюстрация установки — в svg/scenes/kinematics10.js.

import { fmt } from './canvas.js';
import { kinematics10Scene } from '../svg/scenes/kinematics10.js';

const G = 9.8; // м/с² — как в школьных задачниках РК
const rad = (deg) => (deg * Math.PI) / 180;

// Движение раскладывается на два независимых: равномерное по горизонтали со скоростью v₀·cos α
// и равноускоренное по вертикали с начальной скоростью v₀·sin α и ускорением −g.
// Шарик падает на уровень вылета, поэтому время полёта — вдвое больше времени подъёма.
export const flightTime = (p) => (2 * p.v0 * Math.sin(rad(p.alpha))) / G;
export const range = (p) => (p.v0 * p.v0 * Math.sin(rad(2 * p.alpha))) / G;
export const maxHeight = (p) => (p.v0 * Math.sin(rad(p.alpha))) ** 2 / (2 * G);
// Координаты шарика через t секунд после вылета (м, ось y вверх) — по ним сцена рисует траекторию
export const position = (p, t) => ({
  x: p.v0 * Math.cos(rad(p.alpha)) * t,
  y: p.v0 * Math.sin(rad(p.alpha)) * t - (G * t * t) / 2,
});

export default {
  id: 'kinematics10',
  subject: 'physics',
  title: 'Движение тела, брошенного под углом к горизонту',
  freeTitle: 'Баллистический пистолет',
  freeSub: 'Угол вылета, дальность и высота полёта',
  controls: [
    { id: 'alpha', label: 'Угол вылета', min: 15, max: 75, step: 5, unit: '°', value: 15 },
    { id: 'v0', label: 'Начальная скорость', min: 2, max: 4, step: 0.5, unit: 'м/с', value: 4 },
    { id: 'fired', label: 'Пистолет', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['заряжен', 'выстрел сделан'], action: true, actionLabel: 'Выстрелить' },
  ],
  formula: 'L = v₀²·sin 2α / g;  h = v₀²·sin²α / 2g;  t = 2v₀·sin α / g',
  hint: 'Нажмите красный рычаг — пистолет выстрелит. Ствол поворачивайте за рукоятку: после смены угла выстрел повторится сам.',
  chart: { x: 'alpha', y: range, xLabel: 'α, °', yLabel: 'L, м', series: (p) => `v₀ = ${fmt(p.v0, 1)} м/с` },
  theory: 'Движение тела, брошенного под углом α к горизонту, без учёта сопротивления воздуха складывается из двух движений: равномерного по горизонтали со скоростью v₀·cos α и равноускоренного по вертикали с начальной скоростью v₀·sin α и ускорением свободного падения g, направленным вниз. Траектория такого тела — парабола. Если тело падает на уровень, с которого его бросили, время полёта t = 2v₀·sin α / g, наибольшая высота подъёма h = v₀²·sin²α / (2g), дальность полёта L = v₀²·sin 2α / g. Дальность наибольшая при α = 45°, а при углах α и 90° − α она одинакова.',

  readings(p) {
    if (!p.fired) {
      return [
        { label: 'Пистолет', value: 'заряжен' },
        { label: 'Угол α', value: `${p.alpha}°` },
        { label: 'Скорость v₀', value: `${fmt(p.v0, 1)} м/с` },
      ];
    }
    return [
      { label: 'Дальность L', value: `${fmt(range(p))} м` },
      { label: 'Время полёта t', value: `${fmt(flightTime(p), 3)} с` },
      { label: 'Высота подъёма h', value: `${fmt(maxHeight(p))} м` },
      { label: 'Угол α', value: `${p.alpha}°` },
    ];
  },

  describe(p) {
    if (!p.fired) return `Пистолет заряжен; α = ${p.alpha}°, v₀ = ${fmt(p.v0, 1)} м/с`;
    return `α = ${p.alpha}°, v₀ = ${fmt(p.v0, 1)} м/с: дальность L = ${fmt(range(p))} м, время полёта t = ${fmt(flightTime(p), 3)} с, высота подъёма h = ${fmt(maxHeight(p))} м`;
  },

  create(container, params, set) {
    return kinematics10Scene(container, params, set, { range, flightTime, maxHeight, position });
  },
};
