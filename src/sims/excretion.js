// Работа нефрона: фильтрация в капсуле клубочка и обратное всасывание (реабсорбция) в канальцах.
// Ученик берёт пробы из трёх точек модели — плазма крови из почечной артерии, первичная моча
// из капсулы, конечная моча из собирательной трубочки — и сравнивает их состав на анализаторе.
// Состав считается из суточного баланса веществ: через фильтр клубочков за сутки проходит 180 л
// плазмы без белков, а с конечной мочой выводится почти постоянное количество мочевины и солей,
// поэтому их концентрация определяется объёмом мочи. Объём задаёт водный баланс через АДГ,
// а глюкоза появляется в моче, только когда в крови её больше почечного порога (≈ 10 ммоль/л).
// В показаниях — только состав выбранной пробы; объём мочи виден на цилиндре в сцене (svg/scenes/excretion.js).

import { fmt } from './canvas.js';
import { excretionScene } from '../svg/scenes/excretion.js';

export const GFR = 180; // л/сут первичной мочи — значение из учебника (≈ 125 мл/мин)
export const THRESHOLD = 10; // ммоль/л — почечный порог глюкозы: выше него переносчики канальца не успевают
const V_MIN = 0.7; // л/сут — меньше почка не может: моча уже предельно концентрированная

// Суточный вывод с конечной мочой, г: мочевина — конечный продукт обмена белков,
// соли — избыток из пищи, «прочие» — креатинин и мочевая кислота. От выпитой воды почти не зависят.
const UREA_DAY = 27;
const SALT_DAY = 15;
const OTHER_DAY = 3;

// Состав плазмы, % (таблица учебника): белки 7–8%, соли 0,9%, мочевина 0,03%;
// ещё ≈ 1% — жиры и другие крупные вещества, которые в капсулу тоже не проходят
const PLASMA = { protein: 7, salts: 0.9, urea: 0.03, big: 1 };
const PRIMARY_OTHER = 0.1; // аминокислоты, креатинин, мочевая кислота в первичной моче

export const SAMPLES = ['не взята', 'плазма крови', 'первичная моча', 'конечная моча'];

const glucosePct = (mmol) => (mmol * 180) / 10000; // ммоль/л → % (М глюкозы 180 г/моль)

// АДГ выделяет гипофиз, когда воды в организме мало: чем меньше выпито, тем выше уровень (доля 0…1)
export const adhLevel = (p) => Math.min(1, Math.max(0.05, (4.5 - p.water) / 4));
export function adhName(p) {
  const a = adhLevel(p);
  if (a >= 0.85) return 'высокий';
  if (a >= 0.45) return 'средний';
  return 'низкий';
}

// Глюкоза, ушедшая с мочой, ммоль/сут. Порог у разных нефронов немного разный, поэтому сверх порога
// выводится лишь часть избытка — так в учебных примерах при диабете выходит 1–3% глюкозы в моче
export const glucoseLost = (p) => Math.max(0, p.glucose - THRESHOLD) * GFR * 0.3;

// Суточный объём конечной мочи, л. Вода из пищи и от обмена веществ (≈ 1 л) примерно равна потерям
// с потом, дыханием и калом, поэтому мочи выходит столько, сколько выпито. Невсосавшаяся глюкоза
// удерживает воду в канальце (≈ 1 л на 300 ммоль) — отсюда обильная моча при сахарном диабете.
export const urineVolume = (p) => Math.max(V_MIN, p.water) + glucoseLost(p) / 300;

// Состав жидкости в %, sample: 1 — плазма, 2 — первичная, 3 — конечная моча
export function composition(p, sample) {
  const g = glucosePct(p.glucose);
  if (sample === 1) {
    const { protein, salts, urea, big } = PLASMA;
    return { water: 100 - protein - salts - urea - big - g, protein, glucose: g, urea, salts };
  }
  if (sample === 2) {
    const { salts, urea } = PLASMA;
    return { water: 100 - salts - urea - g - PRIMARY_OTHER, protein: 0, glucose: g, urea, salts };
  }
  const V = urineVolume(p);
  const pct = (grams) => grams / (V * 10);
  const glucose = pct((glucoseLost(p) * 180) / 1000);
  const urea = pct(UREA_DAY);
  const salts = pct(SALT_DAY);
  return { water: 100 - urea - salts - glucose - pct(OTHER_DAY), protein: 0, glucose, urea, salts };
}

const pctText = (v, digits) => `${fmt(v, digits)}%`;
const ready = (p, sample) => sample === 1 || (sample > 1 && p.flow === 1);

export default {
  id: 'excretion',
  subject: 'biology',
  title: 'Работа нефрона',
  freeTitle: 'Почка и моча',
  freeSub: 'Фильтрация, реабсорбция, АДГ, глюкоза',
  controls: [
    { id: 'water', label: 'Выпито воды за сутки', min: 0.5, max: 4, step: 0.5, unit: 'л', value: 1.5 },
    { id: 'glucose', label: 'Глюкоза в крови', min: 3, max: 20, step: 1, unit: 'ммоль/л', value: 5 },
    // Действия на сцене: зажим на почечной артерии, пробирки 1, 2 и цилиндр 3
    { id: 'flow', label: 'Кровоток через клубочек', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['перекрыт', 'открыт'], action: true, actionLabel: 'Снять зажим с почечной артерии' },
    { id: 'sample', label: 'Проба', min: 0, max: 3, step: 1, unit: '', value: 0, names: SAMPLES, action: true, actionLabel: 'Взять пробу' },
  ],
  formula: 'кровь → фильтрация → первичная моча → обратное всасывание → конечная моча',
  hint: 'Нажмите на зажим на артерии, затем на пробирки 1, 2 и цилиндр 3 — состав пробы появится под схемой.',
  chart: { x: 'water', y: (p) => Number(urineVolume(p).toFixed(2)), xLabel: 'выпито воды, л/сут', yLabel: 'конечная моча, л/сут', series: (p) => `глюкоза ${p.glucose} ммоль/л` },
  theory: 'Моча образуется в нефронах почки в два этапа. Фильтрация: в клубочке капилляров под давлением крови вода и растворённые в ней мелкие молекулы (глюкоза, аминокислоты, мочевина, соли) переходят в капсулу — образуется первичная моча, около 180 л в сутки. Белки и клетки крови слишком крупные и остаются в крови. Реабсорбция: в извитых канальцах в кровь обратно всасываются вся глюкоза, аминокислоты, большая часть воды и солей. Остаётся 1,5–2 л конечной мочи, в которой мочевины в десятки раз больше, чем в плазме. Всасывание воды в собирательных трубочках усиливает антидиуретический гормон (АДГ) гипофиза: при недостатке воды его выделяется больше, и моча становится концентрированной. Если глюкозы в крови больше почечного порога (около 10 ммоль/л), канальцы не успевают вернуть её в кровь, и она появляется в моче — признак сахарного диабета.',

  readings(p) {
    const s = p.sample;
    const c = ready(p, s) ? composition(p, s) : null;
    // Белка и глюкозы в моче может не быть совсем — тогда так и пишем, а не «0,0%»
    const val = (k, digits) => (!c ? (s === 0 ? '—' : 'проба пуста') : c[k] < 1e-9 ? 'нет' : pctText(c[k], digits));
    return [
      { label: 'Проба', value: SAMPLES[s] },
      { label: 'Белки', value: val('protein', 1) },
      { label: 'Глюкоза', value: val('glucose', 2) },
      { label: 'Мочевина', value: val('urea', 2) },
    ];
  },

  describe(p) {
    const s = p.sample;
    if (s > 1 && !p.flow) return 'Кровоток перекрыт: фильтрации нет, проба пуста';
    if (s === 0) return p.flow ? `Кровоток открыт: за сутки образуется ${GFR} л первичной мочи и ${fmt(urineVolume(p), 1)} л конечной` : 'Кровоток через клубочек перекрыт зажимом';
    const c = composition(p, s);
    if (s === 1) return `Плазма крови: вода ${fmt(c.water, 1)}%, белки ${fmt(c.protein, 1)}%, глюкоза ${fmt(c.glucose, 2)}%, мочевина ${fmt(c.urea, 2)}%, соли ${fmt(c.salts, 2)}%`;
    if (s === 2) return `Первичная моча: вода ${fmt(c.water, 1)}%, белков нет, глюкоза ${fmt(c.glucose, 2)}%, мочевина ${fmt(c.urea, 2)}%, соли ${fmt(c.salts, 2)}%`;
    const glu = c.glucose < 1e-9 ? 'глюкозы нет' : `глюкоза ${fmt(c.glucose, 2)}%`;
    return `Конечная моча ${fmt(urineVolume(p), 1)} л/сут (выпито ${fmt(p.water, 1)} л, АДГ ${adhName(p)}): ${glu}, мочевина ${fmt(c.urea, 2)}%, соли ${fmt(c.salts, 2)}%`;
  },

  create(container, params, set) {
    return excretionScene(container, params, set, { composition, urineVolume, adhLevel, adhName, glucoseLost });
  },
};
