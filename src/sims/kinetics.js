// Скорость реакции тиосульфата натрия с серной кислотой: Na₂S₂O₃ + H₂SO₄ → Na₂SO₄ + S↓ + SO₂↑ + H₂O.
// Колба стоит на листе бумаги с крестом; выделяющаяся сера мутит раствор, и секундомер останавливают,
// когда крест перестаёт быть виден сверху. За это время образуется одно и то же количество серы,
// поэтому скорость реакции обратно пропорциональна времени: v ~ 1/t.
// Кислота взята в избытке, и скорость пропорциональна концентрации тиосульфата (закон действующих масс).
// Зависимость от температуры считается по уравнению Аррениуса, а не по готовому γ: так ученик сам
// находит температурный коэффициент по двум опытам и видит, что правило Вант-Гоффа приближённое
// (γ ≈ 2,2 между 20 и 30 °C и ≈ 2,1 между 30 и 40 °C).
// Иллюстрация установки — в svg/scenes/kinetics.js.

import { fmt } from './canvas.js';
import { kineticsScene } from '../svg/scenes/kinetics.js';

export const C_STOCK = 0.15; // моль/л — исходный раствор тиосульфата
export const TOTAL = 50; // мл — раствор тиосульфата доливают водой до 50 мл, чтобы менялась только концентрация
export const ACID = 10; // мл раствора H₂SO₄ (1 моль/л) — 10 ммоль, больше, чем тиосульфата в любом опыте
// Время исчезновения креста при c = 0,15 моль/л и 20 °C — 24 с, как в типичном школьном опыте;
// отсюда K = t·c = 3,6 с·моль/л
const K = 24 * C_STOCK;
// Энергия активации ≈ 58 кДж/моль — в пределах литературных значений для этой реакции; даёт γ ≈ 2,1–2,2
const EA = 58000;
const R = 8.314;

// Концентрация тиосульфата в колбе после разбавления водой до 50 мл
export const conc = (p) => (C_STOCK * p.V) / TOTAL;

// Время до исчезновения креста, с: обратно пропорционально концентрации и константе скорости k(T)
export const crossTime = (p) => (K / conc(p)) * Math.exp((EA / R) * (1 / (p.T + 273.15) - 1 / 293.15));

export default {
  id: 'kinetics',
  subject: 'chemistry',
  title: 'Скорость реакции тиосульфата натрия с кислотой',
  freeTitle: 'Исчезающий крест',
  freeSub: 'Концентрация, температура, правило Вант-Гоффа',
  controls: [
    { id: 'V', label: 'Объём раствора Na₂S₂O₃', min: 10, max: 50, step: 10, unit: 'мл', value: 50 },
    { id: 'T', label: 'Температура растворов', min: 10, max: 50, step: 5, unit: '°C', value: 20 },
    { id: 'acid', label: 'Серная кислота', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['в цилиндре', 'влита в колбу'], action: true, actionLabel: 'Влить серную кислоту в колбу' },
  ],
  formula: 'Na₂S₂O₃ + H₂SO₄ → Na₂SO₄ + S↓ + SO₂↑ + H₂O;  v ~ 1/t;  v₂/v₁ = γ^((T₂ − T₁)/10)',
  hint: 'Нажмите на цилиндр с кислотой или перетащите его к колбе. Затем меняйте объём тиосульфата и температуру — опыт повторится.',
  chart: { x: 'V', y: (p) => 1 / crossTime(p), xLabel: 'V(Na₂S₂O₃), мл', yLabel: '1/t, с⁻¹', series: (p) => `${p.T} °C` },
  theory: 'Скорость химической реакции — изменение концентрации вещества за единицу времени. Тиосульфат натрия реагирует с серной кислотой: Na₂S₂O₃ + H₂SO₄ → Na₂SO₄ + S↓ + SO₂↑ + H₂O. Выделяющаяся сера делает раствор мутным. Время t, за которое крест под колбой перестаёт быть виден, обратно пропорционально скорости реакции: v ~ 1/t. По закону действующих масс скорость пропорциональна концентрации реагирующего вещества. По правилу Вант-Гоффа при нагревании на каждые 10 °C скорость большинства реакций возрастает в 2–4 раза: v₂ = v₁ · γ^((T₂ − T₁)/10), где γ — температурный коэффициент.',

  readings(p) {
    const t = crossTime(p);
    return [
      { label: 'Концентрация Na₂S₂O₃', value: `${fmt(conc(p))} моль/л` },
      { label: 'Температура', value: `${p.T} °C` },
      { label: 'Время t', value: p.acid ? `${fmt(t, 0)} с` : 'нет кислоты' },
      { label: 'Скорость 1/t', value: p.acid ? `${fmt(1 / t, 4)} с⁻¹` : '—' },
    ];
  },

  describe(p) {
    if (!p.acid) {
      if (p.V === TOTAL) return `В колбе ${p.V} мл раствора Na₂S₂O₃ без воды при ${p.T} °C, кислота не добавлена`;
      return `В колбе ${p.V} мл раствора Na₂S₂O₃ и ${TOTAL - p.V} мл воды при ${p.T} °C, кислота не добавлена`;
    }
    const t = crossTime(p);
    return `c(Na₂S₂O₃) = ${fmt(conc(p))} моль/л, ${p.T} °C: крест исчез через t = ${fmt(t, 0)} с, 1/t = ${fmt(1 / t, 4)} с⁻¹`;
  },

  create(container, params, set) {
    return kineticsScene(container, params, set, { crossTime, conc, TOTAL });
  },
};
