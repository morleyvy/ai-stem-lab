// Проникающая способность ионизирующих излучений: перед торцевым окном счётчика Гейгера на скамье
// ставят источник α-, β- или γ-излучения, а между ними — держатель с пластинами поглотителя
// (бумага, алюминий, свинец). Ученик сравнивает, какое излучение что задерживает, и находит
// слой половинного ослабления свинца для γ-излучения: I = I₀ · 2^(−x/x½).
// Счётчик всегда регистрирует и радиационный фон — его вычитают из показаний.
// Скорость счёта в модели — средняя (без статистического разброса), иначе числа в шагах работы
// не совпадали бы с прибором. Иллюстрация установки — в svg/scenes/nucleus11.js.

import { fmt } from './canvas.js';
import { nucleus11Scene } from '../svg/scenes/nucleus11.js';

export const BACKGROUND = 20; // имп/мин — типичный фон школьного счётчика (космические лучи, радон, стройматериалы)

// Источники из школьного набора. rate — скорость счёта без поглотителя и без фона: у торцевого
// счётчика γ-кванты регистрируются хуже частиц (редко ионизируют газ), поэтому у γ она меньше.
export const SOURCES = [
  { name: 'нет источника', short: '', rate: 0, color: '#94a3b8' },
  { name: 'α-источник (плутоний-239)', short: 'α', rate: 1200, color: '#ef4444' },
  { name: 'β-источник (стронций-90)', short: 'β', rate: 2400, color: '#0ea5e9' },
  { name: 'γ-источник (кобальт-60)', short: 'γ', rate: 800, color: '#8b5cf6' },
];

// Пластины поглотителя: plate — толщина одной пластины (мм), rho — плотность (г/см³),
// gammaHalf — слой половинного ослабления γ-излучения кобальта-60 (мм, по коэффициентам ослабления
// для 1,25 МэВ; для свинца — округлённые 10 мм, как в учебнике: «около 1 см свинца ослабляет γ вдвое»).
export const MATERIALS = [
  { name: 'нет', plate: 0, rho: 0, gammaHalf: Infinity },
  { name: 'бумага', plate: 0.1, rho: 0.8, gammaHalf: 140, color: '#f8fafc' },
  { name: 'алюминий', plate: 1, rho: 2.7, gammaHalf: 47, color: '#cbd5e1' },
  { name: 'свинец', plate: 2, rho: 11.3, gammaHalf: 10, color: '#4b5563' },
];

// β-частицы стронция-90 (с дочерним иттрием-90) теряют энергию на ионизацию: ослабление зависит
// от поверхностной плотности слоя ρx (г/см²), а дальше максимального пробега не проходит ни одна.
const BETA_HALF = 0.135; // г/см² — слой половинного ослабления (0,5 мм алюминия)
const BETA_RANGE = 1.1; // г/см² — максимальный пробег (≈ 4 мм алюминия)

export const source = (p) => SOURCES[p.src];
export const material = (p) => MATERIALS[p.mat];
export const thickness = (p) => (p.mat ? material(p).plate * p.n : 0); // мм

// Доля излучения, прошедшего через поглотитель
export function transmission(p) {
  const x = thickness(p);
  if (!p.src || !x) return 1;
  const m = material(p);
  // Пробег α-частиц в бумаге и металле — сотые доли миллиметра: их задерживает уже один лист
  if (p.src === 1) return 0;
  if (p.src === 2) {
    const areal = (m.rho * x) / 10; // мм → см
    return areal >= BETA_RANGE ? 0 : 2 ** (-areal / BETA_HALF);
  }
  return 2 ** (-x / m.gammaHalf);
}

export const netRate = (p) => source(p).rate * transmission(p);
export const totalRate = (p) => Math.round(netRate(p)) + BACKGROUND;

// Толщина: бумага — десятые доли миллиметра, металлы — целые миллиметры
const thickText = (p) => `${fmt(thickness(p), p.mat === 1 ? 1 : 0)} мм`;
const absorberText = (p) => (p.mat ? `${material(p).name}, ${thickText(p)}` : 'нет');
// Малые и почти полные доли — с десятыми: 0 % и 0,4 %, 99,6 % и 100 % не должны выглядеть одинаково
const pctText = (f) => `${fmt(f * 100, (f > 0 && f < 0.1) || (f > 0.995 && f < 1) ? 1 : 0)} %`;

const sim = {
  id: 'nucleus11',
  subject: 'physics',
  title: 'Поглощение ионизирующего излучения',
  freeTitle: 'Излучение и защита',
  freeSub: 'α, β, γ и поглотители',
  controls: [
    { id: 'counter', label: 'Счётчик Гейгера', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['выключен', 'включён'], action: true, actionLabel: 'Включить счётчик Гейгера' },
    { id: 'src', label: 'Источник излучения', min: 0, max: 3, step: 1, unit: '', value: 0, names: SOURCES.map((x) => x.name), action: true, actionLabel: 'Щёлкнуть по свинцовому контейнеру с источником' },
    { id: 'mat', label: 'Поглотитель', min: 0, max: 3, step: 1, unit: '', value: 0, names: MATERIALS.map((x) => x.name), action: true, actionLabel: 'Щёлкнуть по пластинам поглотителя на полке' },
    { id: 'n', label: 'Число пластин в держателе', min: 1, max: 10, step: 1, unit: 'шт.', value: 5 },
  ],
  formula: 'I = I₀ · 2^(−x / x½)',
  hint: 'Щёлкните по радиометру, затем по контейнеру с источником и по пластинам на полке. Щелчок по источнику или держателю убирает их.',
  chart: { x: 'n', y: netRate, xLabel: 'число пластин', yLabel: 'N − Nф, имп/мин', series: (p) => `${source(p).short || 'фон'}, ${material(p).name}` },
  theory: 'Ионизирующее излучение радиоактивных ядер бывает трёх видов. α-лучи — поток ядер гелия: они сильнее всего ионизируют вещество и поэтому быстро теряют энергию — пролетают в воздухе несколько сантиметров и задерживаются листом бумаги. β-лучи — поток быстрых электронов: проходят бумагу, но задерживаются слоем алюминия в несколько миллиметров. γ-лучи — электромагнитные волны очень малой длины: их проникающая способность самая большая, полностью их не задерживает никакой слой, а только ослабляет. Слой, ослабляющий γ-излучение вдвое, называют слоем половинного ослабления x½; за слоем толщиной x остаётся I = I₀ · 2^(−x/x½). Чем плотнее вещество, тем тоньше этот слой: у свинца для γ-лучей кобальта-60 — около 1 см. Счётчик Гейгера щёлкает и без источника — это радиационный фон (космические лучи, радон, горные породы); его вычитают из показаний. Защита от излучения: экран из плотного вещества, расстояние до источника и меньшее время работы с ним.',

  // Скорость счёта N видна на табло радиометра, фон назван в первом шаге — в панели только то, чего нет в сцене
  readings(p) {
    return [
      { label: 'Источник', value: source(p).name },
      { label: 'Поглотитель', value: absorberText(p) },
      { label: 'Без фона N − Nф', value: p.counter ? `${Math.round(netRate(p))} имп/мин` : '—' },
      { label: 'Прошло', value: p.src ? pctText(transmission(p)) : '—' },
    ];
  },

  describe(p) {
    if (!p.counter) return `${source(p).name}; поглотитель: ${absorberText(p)}; счётчик выключен`;
    return `${source(p).name}; поглотитель: ${absorberText(p)}; N = ${totalRate(p)} имп/мин, без фона ${Math.round(netRate(p))} имп/мин`;
  },

  create(container, params, set) {
    return nucleus11Scene(container, params, set, { SOURCES, MATERIALS, transmission, totalRate });
  },
};

export default sim;
