// Модификационная изменчивость: длина семян фасоли. Фасоль — самоопылитель, семена одного сорта
// (чистой линии) генетически одинаковы, поэтому различия в их длине — модификации, вызванные условиями.
// Измеренные семена ложатся по длине в столбики — получается вариационный ряд,
// по нему строится вариационная кривая и считает среднее M = Σ(v·p)/n. Затем сравнивает семена
// с растений, выросших в тени на бедной почве и на солнце с удобрениями, и сеет мелкие семена
// из тени в обычных условиях: среднее у потомства возвращается к обычному — модификации не наследуются.
// Иллюстрация установки — в svg/scenes/variation.js.

import { fmt } from './canvas.js';
import { variationScene } from '../svg/scenes/variation.js';

export const LENGTH_MIN = 8; // мм — границы шкалы на доске: норма реакции сорта по длине семени
export const LENGTH_MAX = 20;

// Частоты длин (мм → число семян из 100) — как в таблицах практических работ учебника.
// Условия сдвигают ряд целиком, но размах внутри выборки остаётся близким (≈ 8 мм):
// он задан генотипом сорта. У потомства, выращенного в обычных условиях, ряд снова обычный.
const TABLES = {
  shade: { 8: 2, 9: 6, 10: 13, 11: 21, 12: 25, 13: 18, 14: 10, 15: 4, 16: 1 },
  normal: { 10: 1, 11: 4, 12: 11, 13: 19, 14: 27, 15: 19, 16: 12, 17: 5, 18: 2 },
  sun: { 12: 1, 13: 4, 14: 10, 15: 18, 16: 27, 17: 21, 18: 12, 19: 5, 20: 2 },
  kidsShade: { 10: 2, 11: 4, 12: 12, 13: 19, 14: 25, 15: 20, 16: 11, 17: 5, 18: 2 },
  kidsNormal: { 10: 1, 11: 4, 12: 12, 13: 19, 14: 26, 15: 19, 16: 12, 17: 5, 18: 2 },
  kidsSun: { 10: 1, 11: 5, 12: 11, 13: 18, 14: 26, 15: 20, 16: 12, 17: 5, 18: 2 },
};
const SOURCES = [['shade', 'normal', 'sun'], ['kidsShade', 'kidsNormal', 'kidsSun']];

// Короткие названия — значение регулятора под сценой (подробно — в показании «Откуда семена»)
export const BEDS = ['тень', 'обычные', 'солнце'];
// Откуда взяты семена — для показаний и журнала
export const SOURCE_NAMES = [
  ['растения в тени на бедной почве', 'растения в обычных условиях', 'растения на солнце с удобрениями'],
  ['потомство семян из тени в обычных условиях', 'потомство семян из обычных условий', 'потомство семян с солнца в обычных условиях'],
];
export const sourceName = (p) => SOURCE_NAMES[p.gen][p.bed];

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Порядок, в котором семена попадаются под руку, — перемешивание с фиксированным зерном:
// одна и та же выборка всегда даёт одни и те же числа в журнале и в тексте работы
const cache = new Map();
export function seeds(p) {
  const key = `${p.gen}:${p.bed}`;
  if (!cache.has(key)) {
    const list = Object.entries(TABLES[SOURCES[p.gen][p.bed]]).flatMap(([len, k]) => Array(k).fill(Number(len)));
    const rnd = mulberry32(7919 + p.gen * 131 + p.bed * 17);
    for (let i = list.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1));
      [list[i], list[j]] = [list[j], list[i]];
    }
    cache.set(key, list);
  }
  return cache.get(key);
}

// Вариационный ряд первых n измеренных семян: варианта v (мм) → частота p
export function series(p, n = p.n) {
  const freq = new Map();
  for (const v of seeds(p).slice(0, n)) freq.set(v, (freq.get(v) ?? 0) + 1);
  return freq;
}

export function stats(p, n = p.n) {
  if (!n) return null;
  const freq = series(p, n);
  const values = [...freq.keys()].sort((a, b) => a - b);
  let sum = 0;
  let mode = values[0];
  for (const v of values) {
    sum += v * freq.get(v);
    if (freq.get(v) > freq.get(mode)) mode = v;
  }
  return { n, min: values[0], max: values.at(-1), mode, mean: sum / n };
}

