// Осмос в растительной клетке: в растворах разной концентрации соли клетка набухает
// (тургор) или теряет воду (плазмолиз). Изотоническая концентрация в модели — 1% NaCl.
// Вид — как в окуляре микроскопа; иллюстрация — в svg/scenes/osmosis.js.

import { fmt } from './canvas.js';
import { osmosisScene } from '../svg/scenes/osmosis.js';

const ISOTONIC = 1;

// Изменение массы клеток (кусочка ткани) в процентах
export const massChange = (c) => Math.max(-30, -4 * (c - ISOTONIC));

function state(c) {
  if (Math.abs(c - ISOTONIC) < 0.25) return 'изотонический раствор: объём не меняется';
  return c < ISOTONIC ? 'тургор: клетка набухла' : c >= 2 ? 'плазмолиз: цитоплазма отошла от стенки' : 'клетка теряет воду';
}

export const OSMOSIS = {
  id: 'osmosis',
  freeTitle: 'Клетка в растворе',
  freeSub: 'Концентрация соли и осмос',
  freeIcon: 'osmosis',
  subject: 'biology',
  title: 'Осмос',
  controls: [
    { id: 'c', label: 'Концентрация соли в растворе', min: 0, max: 10, step: 0.5, unit: '%', value: 1 },
    // Действие на сцене: винт фокусировки микроскопа; 1 — изображение в окуляре резкое
    { id: 'focus', label: 'Резкость микроскопа', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['не наведена', 'наведена'], action: true, actionLabel: 'Навести резкость' },
  ],
  formula: 'Вода → в сторону большей концентрации растворённых веществ',
  hint: 'Сначала наведите резкость: крутите винт фокусировки на штативе микроскопа — тяните его вверх или вниз (или нажимайте на верхнюю/нижнюю половину), пока клетки в окуляре не станут чёткими. Затем меняйте концентрацию соли регулятором ниже и наблюдайте, как протопласт отходит от клеточной стенки или прижимается к ней.',
  chart: { x: 'c', y: (p) => massChange(p.c), xLabel: 'концентрация NaCl, %', yLabel: 'изменение массы, %', series: () => 'растительная ткань' },
  theory: 'Осмос — движение воды через полупроницаемую мембрану из менее концентрированного раствора в более концентрированный. В чистой воде клетка набухает, в крепком растворе соли теряет воду, и её цитоплазма отходит от клеточной стенки — это плазмолиз.',

  readings(p) {
    const dm = massChange(p.c);
    return [
      { label: 'Изменение массы ткани', value: `${dm > 0 ? '+' : ''}${fmt(dm, 1)}%` },
      { label: 'Состояние клетки', value: p.focus ? state(p.c) : 'не видно — наведите резкость' },
      { label: 'Раствор снаружи', value: `${fmt(p.c, 1)}% NaCl` },
    ];
  },

  describe(p) {
    const dm = massChange(p.c);
    const mass = `Масса ткани изменилась на ${dm > 0 ? '+' : ''}${fmt(dm, 1)}%`;
    // Состояние клеток видно только в резком изображении; массу ткани определяют взвешиванием
    return p.focus ? `${mass} (${state(p.c)})` : `${mass}; изображение в микроскопе размыто — клетки не рассмотреть`;
  },

  create(container, params, set) {
    return osmosisScene(container, params, set, { massChange });
  },
};
