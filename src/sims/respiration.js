// Дыхание прорастающих семян. В плотно закрытой стеклянной банке (≈ 1 л воздуха) лежат семена гороха.
// Живые прорастающие семена дышат: поглощают кислород, выделяют углекислый газ и тепло.
// Через сутки горящая лучинка в банке гаснет, газ из банки мутит известковую воду, а термометр в банке
// показывает больше, чем снаружи. Сухие семена дышат очень слабо, варёные (мёртвые) не дышат совсем.
// Интенсивность дыхания растёт с температурой (примерно вдвое на каждые 10 °C). В банке всегда 100 г семян:
// масса — не предмет опыта, а лишний регулятор только отвлекал бы от сравнения семян и температуры.
// Иллюстрация установки — в svg/scenes/respiration.js.

import { fmt } from './canvas.js';
import { respirationScene } from '../svg/scenes/respiration.js';

export const SEEDS = ['прорастающие', 'сухие', 'варёные'];
// Доля от дыхания прорастающих семян: сухие семена в покое дышат в десятки раз слабее, варёные мертвы
const SEED_FACTOR = [1, 0.02, 0];

const AIR = 1000; // мл воздуха в банке
const MASS = 100; // г семян в банке
const O2_AIR = 21; // % кислорода в воздухе
const CO2_AIR = 0.04; // % углекислого газа в воздухе
// мл O₂ на 1 г семян в час при 20 °C: 100 г прорастающего гороха за сутки поглощают ≈ 0,1 л кислорода
const R20 = 0.04;
const K_O2 = 10; // мл: когда кислорода почти не остаётся, дыхание замедляется (полунасыщение при 1%)
const HEAT_PER_ML = 20.2; // Дж на 1 мл поглощённого O₂ при окислении глюкозы
const LOSS = 0.01; // Вт/°C: банка обёрнута ватой, тепло уходит медленно
const WARMUP = 3; // ч: постоянная времени прогрева и остывания банки

const EXTINGUISH = 16; // % O₂: ниже лучинка гаснет (как свеча под колпаком)
const WEAK = 18; // % O₂: ниже пламя лучинки заметно слабеет

// Температура: каждые 10 °C ускоряют дыхание примерно вдвое; выше 35 °C ферменты начинают разрушаться
export function tempFactor(T) {
  const q = 2 ** ((T - 20) / 10);
  return T > 35 ? q * Math.max(0, 1 - (T - 35) / 15) : q;
}

// Интенсивность дыхания при полном запасе кислорода, мл O₂ в час
export const rate = (p) => R20 * MASS * SEED_FACTOR[p.seeds] * tempFactor(p.T);

// Газ в банке через t часов: кислород убывает, углекислого газа прибавляется столько же (глюкоза: O₂ → CO₂ 1 : 1).
// Заодно считаем, на сколько градусов в банке теплее, чем снаружи: тепло дыхания копится и уходит через обёртку.
// Нагрев интегрируем вместе с газом, а не берём по текущей мощности: когда кислород кончается и дыхание стихает,
// банка остывает постепенно, а не сразу до комнатной температуры.
export function gas(p, t = p.time) {
  const R = rate(p);
  let O = (AIR * O2_AIR) / 100;
  let dT = 0;
  const dt = 0.02;
  for (let s = 0; s < t - 1e-9; s += dt) {
    const h = Math.min(dt, t - s);
    const now = R * (O / (O + K_O2)); // мл O₂ в час
    O -= now * h;
    dT += ((now * HEAT_PER_ML) / 3600 / LOSS - dT) * (h / WARMUP);
  }
  const used = (AIR * O2_AIR) / 100 - O;
  return { o2: (O / AIR) * 100, co2: CO2_AIR + (used / AIR) * 100, dT };
}

export function splintState(o2) {
  if (o2 >= WEAK) return 'продолжает гореть';
  if (o2 >= EXTINGUISH) return 'горит слабее';
  return 'сразу гаснет';
}

export function limeState(co2) {
  if (co2 < 0.5) return 'остаётся прозрачной';
  if (co2 < 3) return 'слегка мутнеет';
  return 'мутнеет';
}

