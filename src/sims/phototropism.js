// Фототропизм проростков овса и ауксин. Горшок с этиолированными проростками стоит в тёмном ящике,
// свет настольной лампы падает только слева, через окошко в стенке. Верхушка колеоптиля воспринимает
// одностороннее освещение, и ауксин, который образуется в верхушке и идёт вниз, перераспределяется
// на теневую сторону. Клетки теневой стороны растягиваются сильнее — проросток изгибается к свету.
// Если верхушку срезать, ауксина нет: проросток почти не растёт и не изгибается; если надеть на верхушку
// непрозрачный колпачок, проросток растёт, но свет не «видит» и остаётся прямым (опыт Ч. Дарвина).
// Иллюстрация установки — в svg/scenes/phototropism.js.

import { fmt } from './canvas.js';
import { phototropismScene } from '../svg/scenes/phototropism.js';

export const L0 = 24; // мм — длина колеоптилей в начале опыта
export const CUT = 3; // мм — сколько отрезают вместе с верхушкой
const GROWTH = 1; // мм/ч — скорость роста колеоптиля овса при достаточном притоке ауксина
const GROWTH_CUT = 0.15; // мм/ч — без верхушки ауксина нет, растяжение клеток почти прекращается
const WIDTH = 3; // мм — толщина колеоптиля: разница удлинения сторон на этой ширине и даёт изгиб
const A_MAX = 0.5; // предельная асимметрия ауксина: 75% на теневой стороне при очень ярком свете
const K_LUX = 500; // лк — освещённость, при которой асимметрия достигает половины предельной

// Варианты обработки верхушек: прозрачный колпачок — контроль к непрозрачному (сам колпачок не мешает)
export const TIPS = ['целые верхушки', 'верхушки удалены', 'непрозрачные колпачки', 'прозрачные колпачки'];

// Воспринимает ли верхушка свет: срезанная или закрытая непрозрачным колпачком — нет
const sensing = (p) => p.light === 1 && (p.tip === 0 || p.tip === 3);

// Асимметрия ауксина, когда верхушка стоит поперёк луча: доля «лишнего» ауксина на теневой стороне
export const asym = (p) => (sensing(p) ? (A_MAX * p.lux) / (p.lux + K_LUX) : 0);

export const growthRate = (p) => (p.tip === 1 ? GROWTH_CUT : GROWTH);

// Угол изгиба к свету, градусы. Теневая сторона растёт со скоростью g(1 + a·cos θ), освещённая — g(1 − a·cos θ):
// чем сильнее верхушка повернулась к лампе, тем равномернее она освещена и тем слабее асимметрия.
// dθ/dt = 2ag·cos θ / d  →  θ(t) = arcsin(th(2ag·t / d)) — изгиб растёт и замедляется у 90°.
export function bend(p, t = p.time) {
  const k = (2 * asym(p) * growthRate(p)) / WIDTH;
  return (Math.asin(Math.tanh(k * t)) * 180) / Math.PI;
}

// Распределение ауксина сейчас, % на теневой и освещённой стороне; null — верхушки нет, ауксин не образуется
export function auxin(p, t = p.time) {
  if (p.tip === 1) return null;
  const a = asym(p) * Math.cos((bend(p, t) * Math.PI) / 180);
  const shade = Math.round(50 * (1 + a));
  return { shade, lit: 100 - shade };
}

export const growth = (p, t = p.time) => growthRate(p) * t;
export const length = (p, t = p.time) => L0 - (p.tip === 1 ? CUT : 0) + growth(p, t);

export default {
  id: 'phototropism',
  subject: 'biology',
  title: 'Фототропизм проростков',
  freeTitle: 'Проростки и свет',
  freeSub: 'Фототропизм, верхушка, ауксин',
  controls: [
    { id: 'lux', label: 'Освещённость', min: 100, max: 1000, step: 100, unit: 'лк', value: 200 },
    { id: 'time', label: 'Время', min: 0, max: 8, step: 1, unit: 'ч', value: 0 },
    // Действия на сцене: выключатель лампы и инструменты на подносе, которые подносят к горшку
    { id: 'light', label: 'Боковая лампа', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['выключена', 'включена'], action: true, actionLabel: 'Включить лампу щелчком по ней' },
    { id: 'tip', label: 'Верхушки проростков', min: 0, max: 3, step: 1, unit: '', value: 0, names: TIPS, action: true, actionLabel: 'Поднести к горшку инструмент с подноса' },
  ],
  formula: 'свет сбоку → ауксин уходит на теневую сторону → её клетки растягиваются сильнее → изгиб к свету',
  hint: 'Щёлкните по лампе, чтобы включить её. Щёлкните по ножницам или колпачкам на подносе. Время и освещённость меняйте регуляторами.',
  chart: { x: 'time', y: (p) => Math.round(bend(p)), xLabel: 't, ч', yLabel: 'угол изгиба, °', series: (p) => (!p.light ? 'лампа выключена' : p.tip === 1 || p.tip === 2 ? TIPS[p.tip] : `${p.lux} лк`) },
  theory: 'Тропизмы — ростовые движения растений в ответ на раздражитель, действующий с одной стороны. Фототропизм — изгиб к свету. Свет воспринимает верхушка колеоптиля: в ней образуется фитогормон ауксин (индолилуксусная кислота), который передвигается вниз, в зону роста, и усиливает растяжение клеток. При одностороннем освещении ауксин перераспределяется на теневую сторону; клетки этой стороны растягиваются сильнее, и проросток изгибается к свету. Это показали опыты Ч. Дарвина (колпачки на верхушках) и Ф. Вента (ауксин из верхушки, собранный в агаровый блок).',

  readings(p) {
    const ax = auxin(p);
    return [
      { label: 'Угол изгиба', value: `${Math.round(bend(p))}°` },
      { label: 'Прирост', value: `${fmt(growth(p), 1)} мм` },
      { label: 'Ауксин в тени', value: ax ? `${ax.shade}%` : 'нет' },
      { label: 'Свет', value: p.light ? `${p.lux} лк` : 'темнота' },
    ];
  },

  describe(p) {
    const t = p.time;
    const g = fmt(growth(p), 1);
    if (t === 0) return p.light ? 'Лампа освещает проростки слева, опыт только начат: проростки ещё прямые' : 'Лампа выключена, опыт не начат: проростки прямые';
    if (p.tip === 1) return `Верхушки удалены: за ${t} ч проростки выросли лишь на ${g} мм и не изогнулись`;
    if (!p.light) return `В темноте за ${t} ч проростки выросли на ${g} мм и остались прямыми`;
    if (p.tip === 2) return `Под непрозрачными колпачками проростки за ${t} ч выросли на ${g} мм, но к свету не изогнулись`;
    const ax = auxin(p);
    const head = p.tip === 3 ? 'Под прозрачными колпачками проростки' : 'Проростки';
    return `${head} за ${t} ч при ${p.lux} лк изогнулись к свету на ${Math.round(bend(p))}°: на теневой стороне ${ax.shade}% ауксина`;
  },

  create(container, params, set) {
    return phototropismScene(container, params, set, { bend, auxin, length });
  },
};
