// Закон сохранения импульса: две тележки на гладкой горизонтальной дорожке. Пусковая пружина разгоняет
// тележку 1 вправо всегда до одной и той же скорости 0,6 м/с (и, если задано, тележку 2 навстречу ей).
// Удар неупругий (игла входит в пластилин, тележки сцепляются) или упругий (стальной пружинный буфер).
// Трение колёс считаем пренебрежимо малым — на время удара система двух тележек замкнута по горизонтали,
// и её импульс сохраняется. Буфер считаем идеально упругим: в школьной модели упругого удара
// кинетическая энергия тоже сохраняется.
// Скорости — проекции на ось x, направленную вправо: знак «минус» значит, что тележка едет влево.
// Иллюстрация установки — в svg/scenes/conservation.js.

import { fmt } from './canvas.js';
import { conservationScene } from '../svg/scenes/conservation.js';

// Пружина тележки 1 не регулируется: так у ученика меньше ползунков, а опыт меняется массами и буфером
export const V1 = 0.6;

// Тележка 2 едет навстречу, то есть влево: проекция её скорости отрицательна
const v2x = (p) => -p.v2;

// Скорости после удара из законов сохранения импульса (и энергии — для упругого удара)
export function afterHit(p) {
  const { m1, m2 } = p;
  const v1 = V1;
  const v2 = v2x(p);
  if (!p.kind) {
    const u = (m1 * v1 + m2 * v2) / (m1 + m2);
    return { u1: u, u2: u };
  }
  return {
    u1: ((m1 - m2) * v1 + 2 * m2 * v2) / (m1 + m2),
    u2: ((m2 - m1) * v2 + 2 * m1 * v1) / (m1 + m2),
  };
}

export const momentum = (p, a, b) => p.m1 * a + p.m2 * b;
export const energy = (p, a, b) => (p.m1 * a * a) / 2 + (p.m2 * b * b) / 2;

// fmt(-0.001, 2) дал бы «-0,00»: такой «минус ноль» сбивал бы ученика
const f = (v, digits = 2) => fmt(Math.abs(v) < 0.5 * 10 ** -digits ? 0 : v, digits);

const KINDS = ['неупругий — тележки сцепляются', 'упругий — пружинный буфер'];

const sim = {
  id: 'conservation',
  freeTitle: 'Столкновение тележек',
  freeSub: 'Импульс и энергия при ударе',
  subject: 'physics',
  title: 'Закон сохранения импульса',
  controls: [
    { id: 'm1', label: 'Масса тележки 1', min: 0.2, max: 1, step: 0.1, unit: 'кг', value: 0.5 },
    { id: 'm2', label: 'Масса тележки 2', min: 0.2, max: 1, step: 0.1, unit: 'кг', value: 0.5 },
    { id: 'v2', label: 'Скорость тележки 2 навстречу', min: 0, max: 0.6, step: 0.1, unit: 'м/с', value: 0 },
    { id: 'kind', label: 'Удар', min: 0, max: 1, step: 1, unit: '', value: 0, names: KINDS, action: true, actionLabel: 'Сменить буфер на тележке 2' },
    { id: 'launched', label: 'Тележки', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['на старте', 'запущены'], action: true, actionLabel: 'Запустить тележки' },
  ],
  formula: 'm₁v₁ + m₂v₂ = m₁u₁ + m₂u₂',
  hint: 'Нажмите на тележку — тележки столкнутся. Нажмите на зелёный пластилин на тележке 2, чтобы сменить удар.',
  theory: 'Импульс тела — произведение его массы на скорость: p = m·v; это векторная величина, её направление совпадает с направлением скорости. В замкнутой системе тел векторная сумма импульсов не меняется при любых взаимодействиях тел системы — закон сохранения импульса: m₁v₁ + m₂v₂ = m₁u₁ + m₂u₂. При неупругом ударе тела после столкновения движутся вместе, и часть кинетической энергии переходит во внутреннюю энергию. При упругом ударе тела расходятся, а их кинетическая энергия сохраняется.',

  readings(p) {
    if (!p.launched) {
      return [
        { label: 'Тележки', value: 'на старте' },
        { label: 'Удар', value: KINDS[p.kind] },
      ];
    }
    const v2 = v2x(p);
    const { u1, u2 } = afterHit(p);
    return [
      { label: 'Скорости до удара', value: `${f(V1)} / ${f(v2)} м/с` },
      p.kind
        ? { label: 'Скорости после удара', value: `${f(u1)} / ${f(u2)} м/с` }
        : { label: 'Общая скорость после', value: `${f(u1)} м/с` },
      { label: 'Импульс до → после', value: `${f(momentum(p, V1, v2))} → ${f(momentum(p, u1, u2))} кг·м/с` },
      { label: 'Энергия до → после', value: `${f(energy(p, V1, v2), 3)} → ${f(energy(p, u1, u2), 3)} Дж` },
    ];
  },

  describe(p) {
    if (!p.launched) return `Тележки у пусковых пружин: m₁ = ${f(p.m1, 1)} кг, m₂ = ${f(p.m2, 1)} кг`;
    const v2 = v2x(p);
    const { u1, u2 } = afterHit(p);
    const before = `v₁ = ${f(V1)} м/с, v₂ = ${f(v2)} м/с`;
    const tail = `импульс ${f(momentum(p, V1, v2))} → ${f(momentum(p, u1, u2))} кг·м/с; Eк ${f(energy(p, V1, v2), 3)} → ${f(energy(p, u1, u2), 3)} Дж`;
    return p.kind
      ? `Упругий удар: ${before} → u₁ = ${f(u1)} м/с, u₂ = ${f(u2)} м/с; ${tail}`
      : `Неупругий удар: ${before} → u = ${f(u1)} м/с; ${tail}`;
  },

  create(container, params, set) {
    return conservationScene(container, params, set, { afterHit, V1 });
  },
};

export default sim;
