// Растворимость солей и её зависимость от температуры. В стакане 100 г воды; ученик насыпает
// шпателем нитрат калия KNO₃ или хлорид натрия NaCl, нагревает и охлаждает водяную баню.
// Растворяется не больше, чем позволяет растворимость при данной температуре (табличные данные
// учебника, г на 100 г воды), остальная соль лежит на дне — раствор насыщенный. При охлаждении
// насыщенного раствора KNO₃ растворимость резко падает, и лишняя соль выпадает в кристаллы:
// их масса равна разности растворимостей. У NaCl растворимость почти не зависит от температуры.
// Вода уже налита в стакан: переливание и фильтрование убраны, чтобы опыт не отвлекал от главного.
// Иллюстрация установки — в svg/scenes/solubility.js.

import { fmt } from './canvas.js';
import { solubilityScene } from '../svg/scenes/solubility.js';

export const SALTS = ['KNO₃', 'NaCl'];

// Растворимость, г на 100 г воды, при 0, 10, …, 100 °C (таблица растворимости в учебнике химии 8 класса)
export const TABLE = [
  [13.3, 20.9, 31.6, 45.8, 63.9, 85.5, 110, 138, 169, 202, 246],
  [35.7, 35.8, 36.0, 36.3, 36.6, 37.0, 37.3, 37.8, 38.4, 39.0, 39.8],
];

// Между точками таблицы — линейная интерполяция (регулятор ходит по 10 °C, но сцена плавно
// меняет температуру, и кристаллы выпадают постепенно, а не скачком)
export function solubility(salt, T) {
  const row = TABLE[salt];
  const t = Math.max(0, Math.min(100, T)) / 10;
  const i = Math.min(9, Math.floor(t));
  return row[i] + (row[i + 1] - row[i]) * (t - i);
}

export const dissolved = (p, T = p.T) => Math.min(p.m, solubility(p.salt, T));
export const excess = (p, T = p.T) => p.m - dissolved(p, T);
// Раствор насыщенный, если на дне лежит соль или соли ровно столько, сколько растворяется
const saturated = (p) => p.m > 0 && solubility(p.salt, p.T) - p.m < 0.05;

export default {
  id: 'solubility',
  subject: 'chemistry',
  title: 'Кривые растворимости',
  freeTitle: 'Растворимость солей',
  freeSub: 'KNO₃ и NaCl, насыщенный раствор, кристаллизация',
  controls: [
    { id: 'salt', label: 'Соль', min: 0, max: 1, step: 1, unit: '', value: 1, names: ['нитрат калия KNO₃', 'хлорид натрия NaCl'], action: true, actionLabel: 'Нажать на банку с другой солью' },
    { id: 'm', label: 'Масса соли в стакане', min: 0, max: 200, step: 5, unit: 'г', value: 0 },
    { id: 'T', label: 'Температура раствора', min: 0, max: 100, step: 10, unit: '°C', value: 20 },
  ],
  formula: 'm(кристаллов) = m(соли) − S(t)',
  hint: 'Перетащите шпатель из банки в стакан — это 10 г соли. Ручку плитки двигайте влево-вправо, по банке щёлкните, чтобы сменить соль.',
  chart: { x: 'T', y: (p) => solubility(p.salt, p.T), xLabel: 't, °C', yLabel: 'растворимость, г на 100 г воды', series: (p) => SALTS[p.salt] },
  theory: 'Растворимость — это наибольшая масса вещества, которая может раствориться в 100 г воды при данной температуре. Раствор, в котором вещество при данной температуре больше не растворяется, называют насыщенным, а раствор, в котором ещё можно растворить вещество, — ненасыщенным. Растворимость большинства твёрдых веществ растёт при нагревании. Зависимость растворимости от температуры изображают кривой растворимости. У нитрата калия она круто поднимается (31,6 г при 20 °C и 169 г при 80 °C), а у хлорида натрия почти горизонтальна (36,0 г и 38,4 г). Поэтому при охлаждении горячего насыщенного раствора KNO₃ выпадают кристаллы: так очищают вещества перекристаллизацией.',

  readings(p) {
    const S = solubility(p.salt, p.T);
    return [
      { label: 'Растворимость', value: `${fmt(S, 1)} г на 100 г воды` },
      { label: 'Растворилось', value: `${fmt(dissolved(p), 1)} г из ${fmt(p.m, 1)} г` },
      { label: 'На дне', value: `${fmt(excess(p), 1)} г` },
      { label: 'Раствор', value: p.m === 0 ? 'соли нет' : saturated(p) ? 'насыщенный' : 'ненасыщенный' },
    ];
  },

  describe(p) {
    const F = SALTS[p.salt];
    const S = solubility(p.salt, p.T);
    if (!p.m) return `В стакане 100 г воды при ${p.T} °C, соли ещё нет`;
    if (excess(p) > 0.05) return `При ${p.T} °C в 100 г воды растворилось ${fmt(S, 1)} г ${F} из ${fmt(p.m, 1)} г, ${fmt(excess(p), 1)} г лежит на дне — раствор насыщенный`;
    if (saturated(p)) return `При ${p.T} °C растворились все ${fmt(p.m, 1)} г ${F} — раствор насыщенный`;
    return `При ${p.T} °C растворились все ${fmt(p.m, 1)} г ${F} — раствор ненасыщенный, можно растворить ещё ${fmt(S - p.m, 1)} г`;
  },

  create(container, params, set) {
    return solubilityScene(container, params, set, { solubility, SALTS });
  },
};
