// Смещение химического равновесия 2NO₂ ⇌ N₂O₄ (ΔH < 0). В запаянном шприце — смесь бурого NO₂
// и бесцветного N₂O₄. Шприц опускают в стаканы со льдом, с водой комнатной температуры и с горячей
// водой, поршень можно вдвигать. Равновесный состав считается по константе равновесия Kc:
//   Kc = [N₂O₄] / [NO₂]²,   c₀ = [NO₂] + 2[N₂O₄]   →   2Kc·x² + x − c₀ = 0,
// а Kc при другой температуре — по уравнению Вант-Гоффа из стандартных величин реакции.
// Поэтому окраска (она пропорциональна [NO₂]) и показания следуют принципу Ле Шателье сами,
// а не заданы для каждого шага.
// Иллюстрация установки — в svg/scenes/equilibrium.js.

import { fmt } from './canvas.js';
import { equilibriumScene } from '../svg/scenes/equilibrium.js';

// Справочные данные (298 К): ΔfG°(NO₂) = 51,3 кДж/моль, ΔfG°(N₂O₄) = 97,9 кДж/моль →
// ΔG° = −4,7 кДж, Kp = exp(−ΔG°/RT) ≈ 6,67 бар⁻¹; ΔH° = 9,2 − 2·33,2 = −57,2 кДж
const DH = -57200; // Дж/моль — реакция экзотермическая
const KP298 = 6.67; // бар⁻¹
const R = 8.314; // Дж/(моль·К)
const RL = 0.08314; // л·бар/(моль·К) — переводит Kp в Kc
// Всего в шприце 3,4 ммоль «звеньев» NO₂ (если бы весь N₂O₄ распался): при 25 °C в 50 мл это давление
// около атмосферного — шприц заполняли при обычном давлении
export const N0 = 3.4e-3; // моль

export const BATHS = [0, 25, 80]; // °C — лёд с водой, вода комнатной температуры, горячая вода
export const bathT = (p) => BATHS[p.bath] ?? 25;

// Kc реакции 2NO₂ ⇌ N₂O₄, л/моль. Kc = Kp·RT, потому что из двух молекул газа получается одна
export function Kc(t) {
  const T = t + 273.15;
  const Kp = KP298 * Math.exp((-DH / R) * (1 / T - 1 / 298.15));
  return Kp * RL * T;
}

// Равновесный состав при температуре t (°C) и объёме V (мл): концентрации, моль/л; количества, моль
export function composition(t, V) {
  const K = Kc(t);
  const c0 = N0 / (V / 1000);
  const no2 = (-1 + Math.sqrt(1 + 8 * K * c0)) / (4 * K);
  const n2o4 = (c0 - no2) / 2;
  return {
    K,
    no2,
    n2o4,
    nNO2: no2 * (V / 1000),
  };
}

// Окраска газа задаётся концентрацией NO₂ (N₂O₄ бесцветен): пороги в ммоль/л
export function colorName(no2) {
  const mm = no2 * 1000;
  if (mm < 7) return 'почти бесцветная';
  if (mm < 15) return 'светло-бурая';
  if (mm < 30) return 'бурая';
  return 'тёмно-бурая';
}

const mmol = (v) => `${fmt(v * 1000, 1)} ммоль/л`;

