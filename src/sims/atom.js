// Конструктор атома: ученик сам набирает протоны, нейтроны и электроны. Элемент определяется
// числом протонов, массовое число — суммой протонов и нейтронов, заряд частицы — разностью
// протонов и электронов. Электроны распределяются по уровням и подуровням по порядку заполнения
// 1s → 2s → 2p → 3s → 3p → 4s → 3d → 4p (с «провалом» электрона у хрома и меди),
// поэтому ученик видит, почему у калия 19-й электрон уходит на 4-й уровень, а не на 3d.
// Данные — для элементов 1–36 (периоды 1–4), как в учебнике химии 10 класса.
// Иллюстрация — в svg/scenes/atom.js.

import { atomScene } from '../svg/scenes/atom.js';

// Символ и название элементов 1–36
