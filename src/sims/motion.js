// Равномерное движение пузырька воздуха в наклонной трубке с водой (7 класс, «Механическое движение»).
// Ученик поднимает конец трубки в лапку штатива, пузырёк ползёт вверх, секундомер запускают у метки 0
// и останавливают у выбранной метки (10, 20, 30 или 40 см). Скорость v = s/t — одна и та же на любом
// участке, значит, движение равномерное; при большем наклоне пузырёк движется быстрее.
// Иллюстрация установки и график s(t) — в svg/scenes/motion.js.

import { fmt } from './canvas.js';
import { motionScene } from '../svg/scenes/motion.js';

// Скорость пузырька в запаянной трубке диаметром около 1 см с водой, см/с, по углу наклона.
// Таблица, а не формула: скорость пузырька в наклонной трубке задаётся трением о стенки и поверхностным
// натяжением, школьной формулы для неё нет. Значения — порядка тех, что получают на уроке; на этом
// участке углов (до 40°) скорость растёт с наклоном, максимум у такой трубки — около 45–50°.
const SPEED = { 10: 2.6, 15: 3.4, 20: 4.1, 25: 4.7, 30: 5.2, 35: 5.6, 40: 5.9 };

export const speed = (p) => SPEED[p.tilt];
// Секундомер запускают, когда пузырёк проходит метку 0, — к этому моменту он уже движется равномерно
export const timeTo = (p, s = p.mark) => s / speed(p);
// 1 см/с = 0,01 м/с
const ms = (v) => v / 100;

export default {
  id: 'motion',
  subject: 'physics',
  title: 'Равномерное движение',
  freeTitle: 'Пузырёк в трубке',
  freeSub: 'Путь, время, скорость, график s(t)',
  controls: [
    { id: 'tilt', label: 'Угол наклона трубки', min: 10, max: 40, step: 5, unit: '°', value: 20 },
    // Метку выбирают щелчком по резиновому кольцу на трубке — у неё секундомер останавливают
    { id: 'mark', label: 'Метка остановки секундомера', min: 10, max: 40, step: 10, unit: 'см', value: 10, action: true, actionLabel: 'Нажать на кольцо у нужной метки' },
    { id: 'run', label: 'Трубка', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['лежит на столе', 'поднята в лапку штатива'], action: true, actionLabel: 'Поднять конец трубки в лапку штатива' },
  ],
  // На доске в сцене строится s(t) для каждого угла; здесь — как скорость зависит от наклона трубки
  chart: { x: 'tilt', y: speed, xLabel: 'угол наклона, °', yLabel: 'v, см/с', series: () => 'скорость пузырька' },
  formula: 'v = s / t;  1 м/с = 3,6 км/ч',
  hint: 'Нажмите на трубку — пузырёк поползёт вверх. Нажмите на кольцо у метки 10–40 см, чтобы выбрать, где остановится секундомер.',
  theory: 'Механическое движение — изменение положения тела относительно других тел с течением времени. Движение, при котором тело за любые равные промежутки времени проходит одинаковые пути, называют равномерным. Скорость равномерного движения равна отношению пути ко времени: v = s / t. В СИ скорость измеряют в метрах в секунду: 1 м/с = 3,6 км/ч, 1 км/ч = 1/3,6 м/с. График пути равномерного движения s(t) — прямая, выходящая из начала координат; чем больше скорость, тем круче прямая.',

  readings(p) {
    if (!p.run) {
      return [
        { label: 'Трубка', value: 'лежит на столе' },
        { label: 'Угол наклона', value: `${p.tilt}°` },
        { label: 'Путь s', value: `${p.mark} см` },
      ];
    }
    const v = speed(p);
    return [
      { label: 'Угол наклона', value: `${p.tilt}°` },
      { label: 'Путь s', value: `${p.mark} см` },
      { label: 'Время t', value: `${fmt(timeTo(p))} с` },
      { label: 'Скорость v', value: `${fmt(v, 1)} см/с = ${fmt(ms(v), 3)} м/с` },
    ];
  },

  describe(p) {
    if (!p.run) return `Трубка лежит на столе, угол лапки ${p.tilt}°: пузырёк стоит у нижнего конца, секундомер не запущен`;
    const v = speed(p);
    return `Угол ${p.tilt}°: путь ${p.mark} см пройден за t = ${fmt(timeTo(p))} с; v = ${fmt(v, 1)} см/с = ${fmt(ms(v), 3)} м/с`;
  },

  create(container, params, set) {
    return motionScene(container, params, set, { speed, timeTo });
  },
};
