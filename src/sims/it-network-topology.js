// Топологии локальной сети: «шина», «звезда», «кольцо» из шести компьютеров A–F.
// Компьютер A отправляет пакет выбранному получателю; модель считает путь пакета, число переходов
// (сколько отрезков кабеля он проходит), число кабелей и то, какие компьютеры теряют связь при обрыве
// кабеля или отказе коммутатора. Правила отказов — как в учебнике информатики 7 класса:
//   шина   — один общий кабель: обрыв в любом месте выводит из строя всю сеть (на оборванном конце
//            нет заглушки-терминатора, сигнал отражается и искажает все передачи);
//   звезда — у каждого компьютера свой кабель к коммутатору: обрыв отключает один компьютер,
//            отказ коммутатора — всю сеть;
//   кольцо — данные идут по кругу в одном направлении, каждый компьютер передаёт их следующему:
//            обрыв в любом месте останавливает передачу по всему кольцу.
// Иллюстрация — в svg/scenes/it-network-topology.js.

import { fmt } from './canvas.js';
import { networkTopologyScene } from '../svg/scenes/it-network-topology.js';

const NODES = ['A', 'B', 'C', 'D', 'E', 'F'];
const N = NODES.length;
const TOPO = ['шина', 'звезда', 'кольцо'];
const TOPO_CAP = ['Шина', 'Звезда', 'Кольцо'];

const BUS = 0;
const STAR = 1;
const RING = 2;

// Получатель: регулятор 0…4 соответствует компьютерам B…F (A — всегда отправитель)
const dstIndex = (p) => p.dst + 1;
// Обрыв: 0 — кабели целы, 1…6 — кабель у компьютера A…F
const cutNode = (p) => (p.cut ? NODES[p.cut - 1] : null);
const hubDown = (p) => p.topo === STAR && Boolean(p.hub);

// Кабели: в шине — один общий (магистраль), в звезде и кольце — по одному на компьютер
const cables = (p) => (p.topo === BUS ? 1 : N);

// Узлы, через которые идёт пакет. В кольце — только по часовой стрелке, через все промежуточные компьютеры.
function route(p) {
  const d = dstIndex(p);
  if (p.topo === STAR) return ['A', 'коммутатор', NODES[d]];
  if (p.topo === BUS) return ['A', 'общий кабель', NODES[d]];
  return NODES.slice(0, d + 1);
}

// Переход — один отрезок кабеля между устройствами. В шине пакет от A сразу идёт по общему кабелю ко всем.
const hops = (p) => (p.topo === STAR ? 2 : p.topo === BUS ? 1 : dstIndex(p));

// Какие компьютеры не могут обмениваться данными ни с одним другим
function lostNodes(p) {
  if (hubDown(p)) return [...NODES];
  if (!p.cut) return [];
  if (p.topo === STAR) return [cutNode(p)];
  return [...NODES];
}

const delivered = (p) => {
  const lost = lostNodes(p);
  return !lost.includes('A') && !lost.includes(NODES[dstIndex(p)]);
};

const pathText = (p) => route(p).join(' → ');
const lostText = (p) => {
  const lost = lostNodes(p);
  if (!lost.length) return `0 из ${N}`;
  if (lost.length === N) return `${N} из ${N}`;
  return `${lost.length} из ${N}: ${lost.join(', ')}`;
};

