// Влияние среды на восстановление перманганата калия. В три пробирки налит одинаковый фиолетовый
// раствор KMnO₄ (Mn⁺⁷): в первую добавлена серная кислота, во вторую — вода, в третью — щёлочь.
// Ученик по каплям приливает восстановитель Na₂SO₃ (S⁺⁴ → S⁺⁶), пока не исчезнет фиолетовая окраска.
// Продукт восстановления марганца зависит от среды: Mn²⁺ (бесцветный), MnO₂ (бурый осадок),
// MnO₄²⁻ (зелёный). Число капель восстановителя считается из электронного баланса и концентраций,
// поэтому расход Na₂SO₃ в трёх средах относится как 5 : 3 : 1 — как числа принятых марганцем электронов.
// Иллюстрация установки — в svg/scenes/redox.js.

import { fmt } from './canvas.js';
import { redoxScene } from '../svg/scenes/redox.js';

const C_OX = 0.01; // моль/л — раствор KMnO₄ (бледно-фиолетовый, как в школьном опыте)
const C_RED = 0.05; // моль/л — раствор Na₂SO₃
const DROP = 0.05; // мл — объём одной капли из пипетки (20 капель в 1 мл)
const S_ELECTRONS = 2; // S⁺⁴ − 2ē → S⁺⁶: каждый сульфит-ион отдаёт 2 электрона

// Три среды: что получается из Mn⁺⁷ и сколько электронов он принимает
export const MEDIA = [
  { id: 'acid', label: 'Пробирка 1 (H₂SO₄)', word: 'кислая', e: 5, result: 'бесцветный, Mn⁺²', half: 'Mn⁺⁷ + 5ē → Mn⁺²' },
  { id: 'water', label: 'Пробирка 2 (H₂O)', word: 'нейтральная', e: 3, result: 'бурый осадок, Mn⁺⁴', half: 'Mn⁺⁷ + 3ē → Mn⁺⁴' },
  { id: 'alkali', label: 'Пробирка 3 (KOH)', word: 'щелочная', e: 1, result: 'зелёный, Mn⁺⁶', half: 'Mn⁺⁷ + ē → Mn⁺⁶' },
];

// Количество KMnO₄ в пробирке, ммоль
export const nOx = (p) => C_OX * p.V;

// Сколько капель Na₂SO₃ нужно, чтобы восстановить весь перманганат: электронов отдано столько же, сколько принято
export function dropsNeeded(p, m) {
  const nRed = (nOx(p) * MEDIA[m].e) / S_ELECTRONS; // ммоль Na₂SO₃
  return Math.round(nRed / C_RED / DROP);
}

const added = (p, m) => p[MEDIA[m].id] === 1;
// «после 1 капли», но «после 2 капель» и «после 10 капель»
const drops = (n) => `${n} ${n === 1 ? 'капли' : 'капель'}`;
const perTube = (p, f) => MEDIA.map((_, m) => (added(p, m) ? String(f(m)) : '—')).join(' / ');

export default {
  id: 'redox',
  subject: 'chemistry',
  title: 'Окислительно-восстановительные реакции перманганата калия',
  freeTitle: 'Перманганат и среда',
  freeSub: 'KMnO₄ + Na₂SO₃ в кислой, нейтральной и щелочной среде',
  controls: [
    { id: 'V', label: 'Объём KMnO₄', min: 0.5, max: 2, step: 0.5, unit: 'мл', value: 1 },
    // Действия на сцене: пипетку с Na₂SO₃ подносят к пробирке (или нажимают на пробирку)
    { id: 'acid', label: 'Пробирка 1 (H₂SO₄)', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['Na₂SO₃ не добавлен', 'Na₂SO₃ добавлен'], action: true, actionLabel: 'Добавить Na₂SO₃ в пробирку с серной кислотой' },
    { id: 'water', label: 'Пробирка 2 (H₂O)', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['Na₂SO₃ не добавлен', 'Na₂SO₃ добавлен'], action: true, actionLabel: 'Добавить Na₂SO₃ в пробирку с водой' },
    { id: 'alkali', label: 'Пробирка 3 (KOH)', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['Na₂SO₃ не добавлен', 'Na₂SO₃ добавлен'], action: true, actionLabel: 'Добавить Na₂SO₃ в пробирку со щёлочью' },
  ],
  formula: 'Mn⁺⁷ → Mn⁺² (H⁺), Mn⁺⁴ (H₂O), Mn⁺⁶ (OH⁻); S⁺⁴ − 2ē → S⁺⁶',
  hint: 'Перетащите пипетку с Na₂SO₃ к пробирке или нажмите на пробирку — раствор капает, пока не исчезнет фиолетовый цвет.',
  theory: 'В окислительно-восстановительных реакциях меняются степени окисления: окислитель принимает электроны и восстанавливается, восстановитель отдаёт электроны и окисляется. Перманганат калия KMnO₄ (Mn⁺⁷) — сильный окислитель, и продукт его восстановления зависит от среды: в кислой — ион Mn²⁺ (раствор обесцвечивается), в нейтральной — бурый осадок MnO₂, в щелочной — зелёный манганат-ион MnO₄²⁻. Сульфит натрия Na₂SO₃ — восстановитель: S⁺⁴ − 2ē → S⁺⁶. Коэффициенты подбирают методом электронного баланса: число электронов, отданных восстановителем, равно числу электронов, принятых окислителем.',

  readings(p) {
    return [
      ...MEDIA.map((m, i) => ({ label: m.label, value: added(p, i) ? m.result : 'фиолетовый, Mn⁺⁷' })),
      { label: 'Капли Na₂SO₃ (1 / 2 / 3)', value: perTube(p, (m) => dropsNeeded(p, m)) },
    ];
  },

  describe(p) {
    const n = MEDIA.map((_, m) => dropsNeeded(p, m));
    if (MEDIA.every((_, m) => added(p, m))) {
      return `При ${fmt(p.V, 1)} мл KMnO₄ израсходовано капель Na₂SO₃: ${n[0]} в кислой среде (бесцветный Mn²⁺), ${n[1]} в нейтральной (бурый MnO₂), ${n[2]} в щелочной (зелёный MnO₄²⁻)`;
    }
    // Описываем последнюю по порядку работы пробирку, в которой прошла реакция: в журнал идёт новое наблюдение
    if (added(p, 2)) return `В щелочной среде после ${drops(n[2])} Na₂SO₃ раствор позеленел: Mn⁺⁷ + ē → Mn⁺⁶`;
    if (added(p, 1)) return `В нейтральной среде после ${drops(n[1])} Na₂SO₃ выпал бурый осадок MnO₂: Mn⁺⁷ + 3ē → Mn⁺⁴`;
    if (added(p, 0)) return `В кислой среде после ${drops(n[0])} Na₂SO₃ раствор обесцветился: Mn⁺⁷ + 5ē → Mn⁺²`;
    return 'В трёх пробирках фиолетовый раствор KMnO₄ (Mn⁺⁷): с серной кислотой, с водой и со щёлочью';
  },

  create(container, params, set) {
    return redoxScene(container, params, set, { MEDIA, dropsNeeded });
  },
};
