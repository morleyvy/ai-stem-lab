// Горение под стеклянным колпаком над водой. Под колпаком заданного объёма сжигают свечу или
// красный фосфор и смотрят, сколько они горят и насколько поднимается вода.
// Свеча гаснет, когда кислорода под колпаком остаётся около 16%, и на месте сгоревшего кислорода
// образуется углекислый газ (парафин: на 3 объёма O₂ — 2 объёма CO₂ и пары воды, которые конденсируются),
// поэтому вода поднимается совсем немного. Фосфор связывает почти весь кислород, а его оксид — твёрдое
// вещество, растворимое в воде, поэтому вода занимает место всего кислорода — около 1/5 объёма.
// Время горения свечи пропорционально запасу кислорода, то есть объёму колпака.
// Иллюстрация установки — в svg/scenes/combustion.js.

import { fmt } from './canvas.js';
import { combustionScene } from '../svg/scenes/combustion.js';

export const O2_AIR = 21; // % кислорода в воздухе по объёму
export const CANDLE_LIMIT = 16; // % — при меньшем содержании кислорода пламя свечи гаснет
// Скорость расхода кислорода, л/с. Свеча сжигает около 0,1 г парафина в минуту — это ≈ 0,3 л O₂ в минуту;
// фосфор в фарфоровой чашечке горит бурно и расходует кислород быстрее
const RATE = [0.005, 0.042];
// Доля израсходованного кислорода, на которую уменьшается объём газа после остывания:
// у свечи вместо 3 объёмов O₂ остаются 2 объёма CO₂ (вода конденсируется), у фосфора оксид — твёрдый
const SHRINK = [1 / 3, 1];

export const FUELS = ['свеча', 'красный фосфор'];

// Сколько кислорода сгорит, в % объёма колпака
export const consumed = (p) => (p.fuel ? O2_AIR : O2_AIR - CANDLE_LIMIT);
export const burnTime = (p) => (p.V * consumed(p)) / 100 / RATE[p.fuel];
// Подъём воды после остывания: мл и % объёма колпака
export const risePct = (p) => consumed(p) * SHRINK[p.fuel];
export const riseMl = (p) => (p.V * 1000 * risePct(p)) / 100;
export const o2Left = (p) => (p.burn ? O2_AIR - consumed(p) : O2_AIR);

// Объём колпака без лишнего нуля: «1 л», «0,5 л»
export const vol = (v) => fmt(v, Number.isInteger(v) ? 0 : 1);

export default {
  id: 'combustion',
  subject: 'chemistry',
  title: 'Горение под колпаком',
  freeTitle: 'Горение под колпаком',
  freeSub: 'Свеча, фосфор, кислород в воздухе',
  controls: [
    { id: 'V', label: 'Объём колпака', min: 0.5, max: 3, step: 0.5, unit: 'л', value: 1 },
    { id: 'fuel', label: 'Горючее вещество', min: 0, max: 1, step: 1, unit: '', value: 0, names: FUELS },
    // Действие на сцене: колпак опускают в воду над подожжённым веществом
    { id: 'burn', label: 'Колпак', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['поднят', 'опущен над горящим веществом'], action: true, actionLabel: 'Поджечь вещество и опустить колпак в воду' },
  ],
  formula: 'вещество + кислород → оксиды; V(O₂) : V(воздуха) ≈ 1 : 5',
  hint: 'Нажмите на колпак — вещество загорится, и колпак опустится в воду. Объём и вещество меняйте регуляторами.',
  chart: { x: 'V', y: (p) => Math.round(burnTime(p)), xLabel: 'V колпака, л', yLabel: 'время горения, с', series: (p) => FUELS[p.fuel] },
  theory: 'Воздух — смесь газов: около 78% азота, 21% кислорода и 1% других газов (аргон, углекислый газ). Горение — реакция вещества с кислородом, при которой выделяются теплота и свет; продукты горения — оксиды. Под колпаком горение прекращается, когда кислорода становится мало. Если сжечь фосфор, который связывает почти весь кислород, вода поднимется примерно на 1/5 объёма колпака — столько в воздухе кислорода. Азот горение не поддерживает. В чистом кислороде вещества горят гораздо энергичнее, чем на воздухе.',

  readings(p) {
    const t = burnTime(p);
    return [
      { label: 'Время горения', value: p.burn ? `${fmt(t, 0)} с` : '—' },
      { label: 'Кислород', value: `${fmt(o2Left(p), 0)}%` },
      { label: 'Подъём воды', value: p.burn ? `${fmt(riseMl(p), 0)} мл, ${fmt(risePct(p), 0)}%` : '—' },
    ];
  },

  describe(p) {
    if (!p.burn) return p.fuel ? `Колпак объёмом ${vol(p.V)} л поднят, красный фосфор ещё не подожжён` : `Колпак объёмом ${vol(p.V)} л поднят, свеча ещё не зажжена`;
    const t = fmt(burnTime(p), 0);
    const ml = fmt(riseMl(p), 0);
    const pct = fmt(risePct(p), 0);
    if (p.fuel) return `Под колпаком ${vol(p.V)} л красный фосфор горел ${t} с и связал весь кислород; вода поднялась на ${ml} мл — ${pct}% объёма, около 1/5`;
    return `Под колпаком ${vol(p.V)} л свеча горела ${t} с и погасла; кислорода осталось ${fmt(o2Left(p), 0)}%, вода поднялась на ${ml} мл — ${pct}% объёма`;
  },

  create(container, params, set) {
    return combustionScene(container, params, set, { burnTime, risePct });
  },
};
