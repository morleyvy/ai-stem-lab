// Неизвестный образец X — поливинилхлорид; в описании нет названия, его ученик выясняет сам
export const UNKNOWN = {
  ...PLASTICS[2],
  short: 'X',
  name: 'неизвестный образец X',
  describe: 'Образец X горит коптящим пламенем с зелёной каймой, вне пламени гаснет; лакмусовая бумажка краснеет — выделяется хлороводород',
};
export const SAMPLES = [...PLASTICS, UNKNOWN];

export const WATER_RHO = 1;

// Насколько образец размягчился при температуре T: 0 — твёрдый, 1 — растёкся.
// Заметно мягким он становится с температуры soft, к soft + 30 °C — вязкая капля.
export function softness(sample, T) {
  if (sample.soft == null) return 0;
  return Math.max(0, Math.min(1, (T - sample.soft + 10) / 40));
}
export const isSoft = (sample, T) => sample.soft != null && T >= sample.soft;
export const floats = (sample) => sample.rho < WATER_RHO;

const shorts = (list) => list.map((x) => x.short).join(', ');
const softList = (T) => SAMPLES.filter((x) => isSoft(x, T));

