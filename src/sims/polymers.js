  // После каждого тире — невидимый «соединитель слов» (U+2060), чтобы перенос строки не разрывал звено
  formula: ['(–CH₂–CH₂–)ₙ', '(–CH₂–CH(C₆H₅)–)ₙ', '(–CH₂–CHCl–)ₙ'].map((u) => u.replaceAll('–', '–⁠')).join('   '),
  hint: 'Нажмите на пробирки, поверните ручку плитки, перетащите кусочек с пластинки в пламя спиртовки.',
  theory: 'Пластмассы — материалы на основе синтетических полимеров. Термопласты (полиэтилен, полистирол, поливинилхлорид) построены из линейных или разветвлённых макромолекул: при нагревании они размягчаются, при охлаждении снова затвердевают, поэтому их можно многократно перерабатывать. Реактопласты (фенолформальдегидные смолы) при отверждении образуют пространственную сетчатую структуру: при нагревании они не размягчаются, а при сильном нагревании разрушаются. Пластмассы распознают по плотности (полиэтилен легче воды), по отношению к нагреванию и по характеру горения. Поливинилхлорид при горении выделяет хлороводород, поэтому влажная синяя лакмусовая бумажка над пламенем краснеет.',

  readings(p) {
    const soft = softList(p.T);
    const b = SAMPLES[p.burn - 1];
    // Температуру плитки показывает её собственный экран в сцене — здесь её не повторяем
    return [
      { label: 'Размягчились', value: soft.length ? shorts(soft) : 'нет' },
      { label: 'В воде', value: p.water ? 'ПЭ плавает, остальные тонут' : '—' },
      { label: 'Горение', value: b ? `${b.short}: ${b.flame}` : '—' },
    ];
  },

  // Журнал записывает последнее проведённое испытание: горение важнее нагревания, нагревание — пробы на плотность
