// Диффузия и отношение площади поверхности к объёму. Кубики агара с фенолфталеином (ребро 1, 2 и 3 см)
// опускают в раствор NaOH: щёлочь диффундирует внутрь, и агар малиновеет от поверхности к центру.
// Через заданное время кубики разрезают и измеряют глубину окраски и долю окрашенного объёма.
// Глубина проникновения растёт как √t (закон диффузии) и одинакова для всех кубиков, а доля окрашенного
// объёма у крупного кубика меньше: при росте ребра S/V = 6/a падает. Поэтому крупным организмам
// одной диффузии через поверхность мало — нужны транспортные системы.
// Иллюстрация установки — в svg/scenes/transport.js.

import { fmt } from './canvas.js';
import { transportScene } from '../svg/scenes/transport.js';

export const EDGES = [1, 2, 3]; // ребро кубиков, см
// мм/√мин: щёлочь проходит ≈ 3 мм за 10 мин — порядок величины школьного опыта с 0,1 М NaOH
// (кубик 1 см прокрашивается почти целиком за урок, кубик 3 см — нет)
const K = 1;

// Глубина окраски, мм: пока кубики не в растворе, щёлочь в них не проникает
export const depth = (p, t = p.time) => (p.immerse ? K * Math.sqrt(t) : 0);

// Доля окрашенного объёма кубика с ребром a (см): неокрашенной остаётся сердцевина-кубик с ребром a − 2d
export function colored(a, d) {
  const core = Math.max(0, a * 10 - 2 * d) / (a * 10);
  return 1 - core ** 3;
}

// Площадь поверхности, объём и их отношение для кубика с ребром a, см
export const area = (a) => 6 * a * a;
export const volume = (a) => a ** 3;
export const ratio = (a) => area(a) / volume(a);

// Время, за которое кубик прокрасится целиком: d = a/2
export const fullTime = (a) => ((a * 10) / 2 / K) ** 2;

// Измеренная глубина: фронты с разных граней встречаются в центре, дальше половины ребра щёлочь не уходит
const reach = (a, d) => Math.min(d, (a * 10) / 2);

const edge = (p) => EDGES[p.size];
const percent = (f) => Math.round(f * 100);

export default {
  id: 'transport',
  subject: 'biology',
  title: 'Диффузия в кубиках агара',
  freeTitle: 'Кубики агара',
  freeSub: 'Диффузия, площадь поверхности и объём',
  controls: [
    { id: 'time', label: 'Время в растворе', min: 0, max: 30, step: 1, unit: 'мин', value: 0 },
    { id: 'size', label: 'Кубик для измерения', min: 0, max: 2, step: 1, unit: '', value: 0, names: ['1 см', '2 см', '3 см'] },
    // Действия на сцене: кубики переносят с плитки в кристаллизатор, скальпель подносят к кубикам
    { id: 'immerse', label: 'Кубики', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['на плитке', 'в растворе'], action: true, actionLabel: 'Опустить кубики в раствор щёлочи' },
    { id: 'cut', label: 'Разрез', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['не сделан', 'сделан'], action: true, actionLabel: 'Разрезать кубики скальпелем' },
  ],
  formula: 'S/V = 6a² / a³ = 6 / a',
  hint: 'Перетащите кубики с плитки в раствор, задайте время и щёлкните по скальпелю — кубики разрежутся. Щелчок по кубику выбирает, какой измерять.',
  chart: { x: 'time', y: (p) => percent(colored(edge(p), depth(p))), xLabel: 't, мин', yLabel: 'окрашено объёма, %', series: (p) => `${edge(p)} см` },
  theory: 'Вещества проникают в клетки и ткани через поверхность и дальше распространяются диффузией. Диффузия идёт быстро только на малых расстояниях: глубина проникновения растёт пропорционально квадратному корню из времени. У кубика с ребром a площадь поверхности S = 6a², объём V = a³, их отношение S/V = 6/a. Чем крупнее тело, тем меньше поверхности приходится на единицу объёма и тем меньшая его доля снабжается за счёт диффузии. Поэтому у крупных многоклеточных организмов есть транспортные системы — кровеносная у животных, проводящая у растений, — а дыхательные и пищеварительные органы имеют огромную поверхность.',

  readings(p) {
    const a = edge(p);
    const d = reach(a, depth(p));
    return [
      { label: 'S/V кубика', value: `${fmt(ratio(a), 1)} см⁻¹` },
      { label: 'Глубина окраски', value: p.cut ? `${fmt(d, 1)} мм` : 'нужен разрез' },
      { label: 'Окрашено объёма', value: p.cut ? `${percent(colored(a, d))}%` : 'нужен разрез' },
      { label: 'Прокрасится целиком', value: `≈ ${fullTime(a)} мин` },
    ];
  },

  describe(p) {
    const a = edge(p);
    const d = reach(a, depth(p));
    if (!p.cut) {
      if (!p.immerse) return 'Кубики агара с фенолфталеином бесцветны: в раствор щёлочи их ещё не опускали';
      if (p.time === 0) return 'Кубики только что опущены в раствор NaOH и ещё бесцветны';
      return `Через ${p.time} мин кубики снаружи стали малиновыми; глубину окраски видно только на разрезе`;
    }
    if (d === 0) return 'На разрезе кубики бесцветны: щёлочь в агар не проникла';
    const f = colored(a, d);
    const head = `Кубик ${a} см (S/V = ${fmt(ratio(a), 1)} см⁻¹), ${p.time} мин в растворе: щёлочь проникла на ${fmt(d, 1)} мм`;
    return f >= 1 ? `${head}, окрашен весь объём` : `${head}, окрашено ${percent(f)}% объёма`;
  },

  create(container, params, set) {
    return transportScene(container, params, set, { depth, colored, EDGES });
  },
};
