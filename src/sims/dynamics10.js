// Сила трения скольжения: деревянный брусок с грузами по 100 г тянут динамометром равномерно
// по доске с разным покрытием (дерево, стекло, резина). При равномерном движении сила упругости пружины
// динамометра уравновешивает силу трения (первый закон Ньютона), поэтому динамометр показывает Fтр.
// Брусок лежит на горизонтальной доске, значит сила нормального давления N = m·g. Коэффициенты трения —
// табличные значения для дерева по этим материалам; модель считает Fтр = μ·N и не зависит от площади опоры —
// это и проверяет ученик, ставя брусок на узкую грань. Иллюстрация установки — в svg/scenes/dynamics10.js.

import { fmt } from './canvas.js';
import { dynamics10Scene } from '../svg/scenes/dynamics10.js';

const G = 9.8; // м/с² — как в школьных задачниках РК
// Коэффициенты трения скольжения деревянного бруска (порядок — как в списке names регулятора surface)
export const MU = [0.3, 0.2, 0.6];
export const SURFACES = ['дерево', 'стекло', 'резина'];
// Брусок 12 × 6 × 3 см: на широкой грани опирается площадью 12·6, на узкой — 12·3
export const AREA = [72, 36];
const FACES = ['широкая', 'узкая'];

export const normal = (p) => (p.m / 1000) * G;
export const friction = (p) => MU[p.surface] * normal(p);

const sim = {
  id: 'dynamics10',
  freeTitle: 'Брусок и динамометр',
  freeSub: 'Сила трения, коэффициент трения',
  subject: 'physics',
  title: 'Сила трения скольжения',
  controls: [
    { id: 'surface', label: 'Поверхность доски', min: 0, max: 2, step: 1, unit: '', value: 0, names: SURFACES },
    { id: 'm', label: 'Масса бруска с грузами', min: 100, max: 500, step: 100, unit: 'г', value: 100 },
    { id: 'side', label: 'Брусок лежит', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['на широкой грани', 'на узкой грани'], action: true, actionLabel: 'Поставить брусок на другую грань' },
    { id: 'pull', label: 'Динамометр', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['не тянут', 'брусок тянут равномерно'], action: true, actionLabel: 'Потянуть брусок динамометром' },
  ],
  formula: 'Fтр = μN;  N = mg;  μ = Fтр / N',
  hint: 'Потяните динамометр вправо. Нажмите на груз — положить или снять, на брусок — сменить грань, на образец — сменить покрытие.',
  chart: { x: 'm', y: friction, xLabel: 'm бруска с грузами, г', yLabel: 'Fтр, Н', series: (p) => SURFACES[p.surface] },
  theory: 'Когда одно тело скользит по поверхности другого, возникает сила трения скольжения. Она направлена против движения и пропорциональна силе нормального давления: Fтр = μN, где μ — коэффициент трения. Он зависит от материалов и обработки соприкасающихся поверхностей и почти не зависит от площади их соприкосновения. Если брусок тянуть равномерно, по первому закону Ньютона сила упругости пружины динамометра равна силе трения. На горизонтальной поверхности N = mg.',

  readings(p) {
    const n = normal(p);
    // Пока брусок не тянут, трение покоя не измеряется — динамометр показывает 0, μ не определён
    const f = p.pull ? friction(p) : 0;
    return [
      { label: 'Динамометр Fтр', value: `${fmt(f)} Н` },
      { label: 'N = mg', value: `${fmt(n)} Н` },
      { label: 'Площадь опоры', value: `${AREA[p.side]} см²` },
      { label: 'μ = Fтр/N', value: p.pull ? fmt(f / n) : '—' },
    ];
  },

  describe(p) {
    const where = `Поверхность: ${SURFACES[p.surface]}, m = ${p.m} г, ${FACES[p.side]} грань (S = ${AREA[p.side]} см²)`;
    if (!p.pull) return `${where}: брусок покоится, динамометр показывает 0 Н`;
    const f = friction(p);
    const n = normal(p);
    return `${where}: Fтр = ${fmt(f)} Н, N = ${fmt(n)} Н, μ = Fтр/N = ${fmt(f / n)}`;
  },

  create(container, params, set) {
    return dynamics10Scene(container, params, set, { friction });
  },
};

export default sim;
