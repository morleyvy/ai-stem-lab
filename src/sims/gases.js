// Получение кислорода разложением пероксида водорода: 2H₂O₂ → 2H₂O + O₂↑. В колбу с отводом налито
// 5 мл раствора H₂O₂; ученик вносит шпателем оксид марганца(IV) MnO₂, газ по отводу идёт в газовый шприц,
// и по поршню видно, сколько кислорода собралось к данной минуте. В конце газ проверяют тлеющей лучинкой.
// Объём считается по уравнению реакции (из массы пероксида), скорость — как у реакции первого порядка:
// константа пропорциональна массе катализатора (больше порошка — больше поверхности), а общий объём
// кислорода от катализатора не зависит. Так ученик видит главное свойство катализатора: он ускоряет
// реакцию, но не расходуется и не меняет количество продукта.
// Иллюстрация установки — в svg/scenes/gases.js.

import { fmt } from './canvas.js';
import { gasesScene } from '../svg/scenes/gases.js';

export const SOLUTION_ML = 5; // мл раствора в колбе; плотность разбавленного раствора ≈ 1 г/мл
const M_H2O2 = 34; // г/моль
const VM = 22400; // мл/моль — молярный объём газа при н. у., как в задачах 8 класса
// 1/(мин·г): с 0,5 г MnO₂ половина пероксида разлагается примерно за минуту, как в школьном опыте
const K_CAT = 1.4;
// 1/мин: без катализатора разбавленный пероксид разлагается месяцами — за урок газа не видно
const K_SELF = 1e-4;
export const SPLINT_MIN = 5; // мл — меньше этого кислорода лучинке нечего поджигать

// Сколько кислорода может дать весь пероксид в колбе: n(O₂) = n(H₂O₂) / 2
export const totalO2 = (p) => ((SOLUTION_ML * p.c) / 100 / M_H2O2 / 2) * VM;

const k = (p) => (p.catalyst ? K_CAT * p.m : K_SELF);

// Доля разложившегося пероксида к моменту t
export const decomposed = (p, t = p.time) => 1 - Math.exp(-k(p) * t);

// Объём кислорода в шприце к моменту t, мл
export const volume = (p, t = p.time) => totalO2(p) * decomposed(p, t);

// Скорость выделения газа в момент t, мл/мин: со временем падает — пероксида становится меньше
export const rate = (p, t = p.time) => k(p) * totalO2(p) * Math.exp(-k(p) * t);

