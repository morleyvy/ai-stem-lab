// Трансформатор (11 класс, «Переменный ток»). Лабораторный источник переменного напряжения 50 Гц
// питает первичную обмотку, у обеих обмоток есть отводы с разным числом витков. Ученик включает
// источник, переставляет штекеры по отводам и подключает ключом реостат во вторичную цепь.
// Показания приборов — только в панели под сценой, чтобы на столе остался один трансформатор.
//
// Модель — трансформатор с потерями, достаточная для школьных измерений:
// - ЭДС обмоток пропорциональны числу витков (один и тот же магнитный поток в сердечнике);
// - активное сопротивление провода пропорционально числу витков — из-за него под нагрузкой
//   U₂ немного падает и КПД меньше 100 %;
// - ток холостого хода (намагничивающий) сдвинут по фазе на 90° относительно тока нагрузки,
//   поэтому амперметр показывает I₁ = √(I₁нагр² + I₀²); индуктивное сопротивление первичной
//   обмотки растёт как N₁². Насыщение сердечника и вихревые токи не учитываем.
// Коэффициент трансформации — как в учебниках РК: k = N₁/N₂ = U₁/U₂ (k > 1 — понижающий).
// Иллюстрация установки — в svg/scenes/ac-current.js.

import { fmt } from './canvas.js';
import { acCurrentScene } from '../svg/scenes/ac-current.js';

export const N1S = [100, 200, 400]; // отводы первичной обмотки, витков
export const N2S = [50, 100, 200, 400]; // отводы вторичной обмотки, витков
const RHO = 0.002; // Ом на виток: у обмотки 200 витков сопротивление 0,4 Ом
const X200 = 600; // Ом — индуктивное сопротивление первичной обмотки 200 витков на 50 Гц

export const turns = (p) => ({ N1: N1S[p.N1], N2: N2S[p.N2] });

// Все показания приборов в одном месте: и для панели показаний, и для сцены
export function state(p) {
  const { N1, N2 } = turns(p);
  const k = N1 / N2;
  if (!p.power) return { N1, N2, k, U1: 0, U2: 0, I1: 0, I2: 0, P1: 0, P2: 0, eta: 0 };
  const n = N2 / N1;
  const U1 = p.U1;
  // Сопротивление первичной обмотки, приведённое ко вторичной, — n²·r₁
  const I2 = p.load ? (n * U1) / (p.R + RHO * N2 + n * n * RHO * N1) : 0;
  const U2 = p.load ? I2 * p.R : n * U1;
  const I0 = U1 / (X200 * (N1 / 200) ** 2);
  const I1 = Math.hypot(n * I2, I0);
  const P1 = U1 * I1;
  const P2 = U2 * I2;
  return { N1, N2, k, U1, U2, I1, I2, P1, P2, eta: P1 > 0 ? P2 / P1 : 0 };
}

const kind = (k) => (k > 1 ? 'понижающий' : k < 1 ? 'повышающий' : 'не меняет напряжение');

export default {
  id: 'ac-current',
  subject: 'physics',
  title: 'Трансформатор',
  freeTitle: 'Трансформатор',
  freeSub: 'Витки, напряжение, ток, КПД',
  controls: [
    { id: 'U1', label: 'Напряжение источника U₁', min: 1, max: 12, step: 1, unit: 'В', value: 4 },
    { id: 'R', label: 'Сопротивление нагрузки', min: 10, max: 50, step: 5, unit: 'Ом', value: 20 },
    // Действия на сцене: тумблер источника, штекеры на отводах обмоток, ключ во вторичной цепи
    { id: 'power', label: 'Источник напряжения', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['выключен', 'включён'], action: true, actionLabel: 'Включить источник тумблером' },
    { id: 'N1', label: 'Первичная обмотка', min: 0, max: 2, step: 1, unit: '', value: 1, names: ['100 витков', '200 витков', '400 витков'], action: true, actionLabel: 'Переставить штекер на отвод первичной обмотки' },
    { id: 'N2', label: 'Вторичная обмотка', min: 0, max: 3, step: 1, unit: '', value: 1, names: ['50 витков', '100 витков', '200 витков', '400 витков'], action: true, actionLabel: 'Переставить штекер на отвод вторичной обмотки' },
    { id: 'load', label: 'Нагрузка', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['отключена', 'подключена'], action: true, actionLabel: 'Замкнуть ключ во вторичной цепи' },
  ],
  formula: 'k = N₁ / N₂ = U₁ / U₂;  η = U₂I₂ / U₁I₁',
  hint: 'Нажмите тумблер источника, гнёзда «50…400» на обмотках и ключ справа; реостат тяните мышью.',
  theory: 'Трансформатор состоит из замкнутого стального сердечника и двух обмоток. Переменный ток в первичной обмотке создаёт в сердечнике переменный магнитный поток, который наводит ЭДС в каждом витке обеих обмоток. Поэтому при холостом ходе U₁ / U₂ = N₁ / N₂ = k — коэффициент трансформации; при k > 1 трансформатор понижающий, при k < 1 — повышающий. Потери энергии в трансформаторе малы: U₁I₁ ≈ U₂I₂, КПД η = P₂ / P₁ обычно больше 90 %.',

  readings(p) {
    const st = state(p);
    if (!p.power) {
      return [
        { label: 'Источник напряжения', value: 'выключен' },
        { label: 'Число витков N₁ / N₂', value: `${st.N1} / ${st.N2}` },
        { label: 'Трансформатор', value: kind(st.k) },
      ];
    }
    // Четыре строки: КПД ученик считает сам по U и I, а в журнал он попадает из describe()
    const head = [
      { label: 'Напряжение U₁', value: `${fmt(st.U1, 1)} В` },
      { label: 'Сила тока I₁', value: `${fmt(st.I1, 3)} А` },
      { label: 'Напряжение U₂', value: `${fmt(st.U2)} В` },
    ];
    if (!p.load) return [...head, { label: 'k = N₁ / N₂', value: `${fmt(st.k)} (${kind(st.k)})` }];
    return [...head, { label: 'Сила тока I₂', value: `${fmt(st.I2, 3)} А` }];
  },

  describe(p) {
    const st = state(p);
    if (!p.power) return `Источник выключен — тока в обмотках нет; N₁ = ${st.N1}, N₂ = ${st.N2}`;
    if (!p.load) {
      return `Холостой ход, N₁ = ${st.N1}, N₂ = ${st.N2}: U₁ = ${fmt(st.U1, 1)} В, U₂ = ${fmt(st.U2)} В, U₁/U₂ = ${fmt(st.U1 / st.U2)}; I₁ = ${fmt(st.I1, 3)} А`;
    }
    return `Нагрузка ${p.R} Ом: U₁ = ${fmt(st.U1, 1)} В, I₁ = ${fmt(st.I1, 3)} А, U₂ = ${fmt(st.U2)} В, I₂ = ${fmt(st.I2, 3)} А; P₁ = ${fmt(st.P1)} Вт, P₂ = ${fmt(st.P2)} Вт, η = ${fmt(st.eta * 100, 0)} %`;
  },

  create(container, params, set) {
    return acCurrentScene(container, params, set, { state, N1S, N2S });
  },
};
