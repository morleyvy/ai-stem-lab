// Устройство компьютера: ученик собирает системный блок — ставит в открытый корпус блок питания,
// процессор, оперативную память, накопитель SSD и (по желанию) видеокарту — и нажимает кнопку питания.
// Порядок проверки при включении — как у настоящего компьютера: сначала нужно питание, затем процессор,
// затем оперативная память (без неё проверка при включении останавливается), затем накопитель с системой.
// Видеокарта не обязательна: в школьных и офисных компьютерах изображение выводит графика,
// встроенная в процессор. Модель не помнит прошлых состояний: ОЗУ без питания всегда пуста,
// а накопитель хранит систему и файлы независимо от питания.
// Иллюстрация — в svg/scenes/it-pc-assembly.js.

import { pcAssemblyScene } from '../svg/scenes/it-pc-assembly.js';

// Обязательные детали в том порядке, в каком компьютер проверяет их при включении
export const REQUIRED = [
  { id: 'psu', name: 'блок питания' },
  { id: 'cpu', name: 'процессор' },
  { id: 'ram', name: 'ОЗУ' },
  { id: 'ssd', name: 'накопитель' },
];

const missing = (p) => REQUIRED.filter((c) => !p[c.id]);

// Что происходит после нажатия кнопки: 'off' — выключен, 'nopower' — нет блока питания,
// 'cpu' / 'ram' / 'boot' — остановился на этой проверке, 'ok' — работает
export function stage(p) {
  if (!p.power) return 'off';
  if (!p.psu) return 'nopower';
  if (!p.cpu) return 'cpu';
  if (!p.ram) return 'ram';
  if (!p.ssd) return 'boot';
  return 'ok';
}

const STATUS = {
  off: 'выключен',
  nopower: 'не включается: нет блока питания',
  cpu: 'не запускается: нет процессора',
  ram: 'не запускается: нет оперативной памяти',
  boot: 'не загружается: нет накопителя с системой',
  ok: 'работает',
};

const yesNo = (names) => ['нет', ...names];

export default {
  id: 'it-pc-assembly',
  freeTitle: 'Сборка компьютера',
  freeSub: 'Процессор, память, накопитель, питание',
  freeIcon: 'binary',
  subject: 'informatics',
  title: 'Устройство компьютера',
  controls: [
    { id: 'psu', label: 'Блок питания', min: 0, max: 1, step: 1, unit: '', value: 0, names: yesNo(['установлен']), action: true, actionLabel: 'Перетащить блок питания в корпус' },
    { id: 'cpu', label: 'Процессор', min: 0, max: 1, step: 1, unit: '', value: 0, names: yesNo(['установлен']), action: true, actionLabel: 'Перетащить процессор в разъём на плате' },
    { id: 'ram', label: 'Оперативная память', min: 0, max: 1, step: 1, unit: '', value: 0, names: yesNo(['установлена']), action: true, actionLabel: 'Перетащить планку ОЗУ в слот на плате' },
    { id: 'ssd', label: 'Накопитель SSD', min: 0, max: 1, step: 1, unit: '', value: 0, names: yesNo(['установлен']), action: true, actionLabel: 'Перетащить SSD в отсек корпуса' },
    { id: 'gpu', label: 'Видеокарта', min: 0, max: 1, step: 1, unit: '', value: 0, names: yesNo(['установлена']), action: true, actionLabel: 'Перетащить видеокарту в длинный слот на плате' },
    { id: 'power', label: 'Питание', min: 0, max: 1, step: 1, unit: '', value: 0, names: ['выключено', 'включено'], action: true, actionLabel: 'Нажать кнопку питания на корпусе' },
  ],
  formula: 'Компьютер запускается, если есть: блок питания + процессор + ОЗУ + накопитель с системой',
  hint: 'Перетащите детали с полок в корпус и нажмите кнопку питания. Щелчок по установленной детали вернёт её на полку.',
  theory: 'Системный блок компьютера собирают на материнской плате — она соединяет все устройства между собой. Процессор обрабатывает данные: выполняет команды программ, считает и сравнивает. Оперативная память (ОЗУ) хранит программы и данные, с которыми процессор работает прямо сейчас; она очень быстрая, но при выключении питания очищается. Накопитель — жёсткий диск (HDD) или твердотельный SSD — хранит операционную систему, программы и файлы долговременно, даже без питания. Блок питания преобразует ток из розетки в низкое напряжение и питает все детали. Видеокарта формирует изображение для монитора; во многих компьютерах её заменяет графика, встроенная в процессор. Без блока питания, процессора или оперативной памяти компьютер не запустится, а без накопителя ему неоткуда загрузить операционную систему.',

  // Четыре строки: состояние компьютера, чего не хватает и где сейчас данные — в ОЗУ и на накопителе.
  // Что установлено, видно на самой сцене, поэтому список деталей не повторяем
  readings(p) {
    const st = stage(p);
    const lack = missing(p);
    return [
      { label: 'Компьютер', value: STATUS[st] },
      { label: 'Не хватает', value: lack.length ? lack.map((c) => c.name).join(', ') : 'ничего' },
      { label: 'Данные в ОЗУ', value: !p.ram ? 'нет ОЗУ' : st === 'ok' ? 'система и открытые программы' : 'пусто' },
      { label: 'Данные на накопителе', value: p.ssd ? 'система и файлы сохранены' : 'нет накопителя' },
    ];
  },

  describe(p) {
    const lack = missing(p);
    const video = p.gpu ? 'изображение выводит видеокарта' : 'изображение выводит графика, встроенная в процессор';
    switch (stage(p)) {
      case 'off':
        return lack.length
          ? `Компьютер выключен, не хватает: ${lack.map((c) => c.name).join(', ')}`
          : 'Компьютер собран и выключен: оперативная память пуста, система и файлы хранятся на накопителе';
      case 'nopower':
        return 'Кнопка нажата, но ничего не происходит: без блока питания детали не получают ток';
      case 'cpu':
        return 'Вентилятор блока питания крутится, но компьютер не запускается: нет процессора — некому выполнять команды';
      case 'ram':
        return 'Процессор получил питание, но компьютер не запускается: нет оперативной памяти — процессору негде держать данные';
      case 'boot':
        return 'Процессор и память работают, но системы нет: без накопителя неоткуда загрузить операционную систему';
      default:
        return `Компьютер работает: система загружена с накопителя в ОЗУ, процессор выполняет её команды, ${video}`;
    }
  },

  create(container, params, set) {
    return pcAssemblyScene(container, params, set, { stage });
  },
};
