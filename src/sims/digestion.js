// Действие амилазы слюны на крахмал. В пробирке с крахмальным клейстером, стоящей в водяной бане,
// амилаза расщепляет крахмал до мальтозы. Каждую минуту каплю смеси переносят на белую пластинку
// с йодом: пока крахмала много, проба тёмно-синяя, по мере расщепления — фиолетовая, красно-бурая
// (декстрины) и, наконец, жёлто-бурая — цвет самого йода, крахмала больше нет.
// Скорость расщепления зависит от температуры (оптимум — температура тела, при кипячении фермент
// денатурирует) и от pH (в кислой среде желудка амилаза слюны не работает).
// Иллюстрация установки — в svg/scenes/digestion.js.

import { fmt } from './canvas.js';
import { digestionScene } from '../svg/scenes/digestion.js';

const K_MAX = 1; // 1/мин: при 37 °C и pH 7 синяя окраска исчезает за ≈ 3 мин, как в школьном опыте с разбавленной слюной
const CLEAR = 0.05; // меньше 5% крахмала йод уже не окрашивает в синий цвет

// Температура: ниже оптимума фермент просто замедляется (на холоде — в десятки раз),
// выше — белок денатурирует; к 70 °C активность исчезает полностью и необратимо
export function tempFactor(T) {
  if (T <= 37) return Math.exp((T - 37) / 12);
  const bell = Math.exp(-(((T - 37) / 12) ** 2));
  return T > 55 ? bell * Math.max(0, 1 - (T - 55) / 15) : bell;
}

// pH: амилаза слюны работает в нейтральной и слабощелочной среде, в кислой (pH 2, как в желудке) — нет
export const phFactor = (pH) => Math.exp(-(((pH - 7) / 1.5) ** 2));

// Без слюны фермента в пробирке нет — крахмал не расщепляется
export const activity = (p) => (p.saliva ? tempFactor(p.T) * phFactor(p.pH) : 0);

// Доля крахмала, оставшаяся через t минут после добавления слюны (реакция первого порядка)
export const starchLeft = (p, t = p.time) => Math.exp(-K_MAX * activity(p) * t);

// Цвет пробы с йодом по оставшемуся крахмалу: крахмал → декстрины → мальтоза
export function iodineColor(S) {
  if (S >= 0.6) return 'тёмно-синяя';
  if (S >= 0.25) return 'фиолетовая';
  if (S >= CLEAR) return 'красно-бурая';
  return 'жёлто-бурая';
}

// Время, за которое синяя окраска исчезает (крахмала < 5%); Infinity — фермент не работает
export function clearTime(p) {
  const k = K_MAX * activity(p);
  return k < 1e-3 ? Infinity : Math.log(1 / CLEAR) / k;
}

