  hint: 'Перетащите капельницу с йодом к белой пластинке, а пипетку со слюной — к пробирке. Затем меняйте время, температуру и pH.',
  chart: { x: 'T', y: (p) => Math.round(activity(p) * 100), xLabel: 'T, °C', yLabel: 'активность, %', series: (p) => (p.saliva ? `pH ${p.pH}` : 'без слюны') },
